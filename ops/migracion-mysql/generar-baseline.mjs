// Genera el baseline de Flyway para PostgreSQL a partir del esquema final de MySQL.
//
// Herramienta historica de la migracion MySQL -> PostgreSQL (11/11/2026). No forma parte de la
// aplicacion: corrio una vez para escribir V2..V12 de src/main/resources/db/migration, que despues
// se revisaron a mano. Se conserva para poder repetir la traduccion y auditarla.
//
// Entradas:
//   mysql-schema.json   information_schema de una base MySQL con las 145 migraciones aplicadas
//                       (ver ops/migracion-mysql/README.md, paso 1)
//   hibernate-pg.sql    DDL que Hibernate espera para PostgreSQL, exportado desde las entidades
//                       (paso 2). De ahi salen los tipos: Instant -> timestamptz, boolean, jsonb.
//   tabla-modulo.txt    "tabla modulo" por cada @Table
// Salida: un archivo por migracion en el directorio indicado.
//
// Uso: node generar-baseline.mjs <dir-entradas> <dir-salida>

import fs from 'node:fs';
import path from 'node:path';

const [entradas, salida] = process.argv.slice(2);
const leer = (f) => fs.readFileSync(path.join(entradas, f), 'utf8');
const j = JSON.parse(leer('mysql-schema.json'));

// ---------------------------------------------------------------- tipos que espera Hibernate
const hib = {};
for (const linea of leer('hibernate-pg.sql').split('\n')) {
	const m = linea.match(/^create table (\w+) \((.*)\);$/);
	if (!m) continue;
	const cols = {};
	// Las columnas vienen separadas por ", " fuera de parentesis.
	let prof = 0, actual = '';
	const partes = [];
	for (const ch of m[2]) {
		if (ch === '(') prof++;
		if (ch === ')') prof--;
		if (ch === ',' && prof === 0) { partes.push(actual.trim()); actual = ''; continue; }
		actual += ch;
	}
	partes.push(actual.trim());
	for (const p of partes) {
		const c = p.match(/^(\w+) (.+?)(?: generated by default as identity)?(?: not null)?(?: check .*)?$/);
		if (!c || c[1] === 'primary') continue;
		cols[c[1]] = c[2].replace(/ not null.*$/, '').replace(/ check .*$/, '');
	}
	hib[m[1]] = cols;
}

const modulo = Object.fromEntries(leer('tabla-modulo.txt').trim().split('\n').map((l) => l.split(' ')));
modulo.biblioteca_version = 'knowledge';
modulo.platform_schema_info = 'platform';

// ---------------------------------------------------------------- utilidades
const porTabla = (lista) => {
	const r = {};
	for (const x of lista || []) (r[x.t] ||= []).push(x);
	return r;
};
const columnas = porTabla(j.columns);
for (const t in columnas) columnas[t].sort((a, b) => a.pos - b.pos);
const comentarioTabla = Object.fromEntries(j.tables.map((t) => [t.t, t.comment]));
const lit = (s) => `'${String(s).replace(/'/g, "''")}'`;

const esTexto = (c) => ['varchar', 'char', 'text', 'mediumtext', 'longtext'].includes(c.dt);

function tipoPg(c) {
	const h = hib[c.t]?.[c.c];
	if (c.t === 'libro_fragmento' && c.c === 'vector') return 'vector(768)';
	switch (c.dt) {
		case 'bigint': return 'bigint';
		case 'int': return 'integer';
		case 'smallint': return 'smallint';
		case 'tinyint':
			if (c.type === 'tinyint(1)') return h === 'smallint' ? 'smallint' : 'boolean';
			return 'smallint';
		case 'decimal': return `numeric(${c.prec},${c.scale})`;
		case 'double': return 'double precision';
		case 'float': return 'real';
		case 'varchar':
		case 'char': return `varchar(${c.len})`;
		case 'text': case 'mediumtext': case 'longtext': return 'text';
		case 'blob': case 'longblob': case 'mediumblob': return 'bytea';
		case 'json': return 'jsonb';
		case 'date': return 'date';
		case 'time': return 'time';
		case 'datetime':
		case 'timestamp':
			// Un Instant es un instante: timestamptz. Un LocalDateTime seria timestamp sin zona; hoy no
			// hay ninguno mapeado. Las columnas sin entidad (las *_key generadas) siguen a su base.
			if (h && h.startsWith('timestamp(6)') && !h.includes('time zone')) return 'timestamp(6)';
			return 'timestamptz(6)';
		default: throw new Error(`tipo sin mapear ${c.t}.${c.c} ${c.type}`);
	}
}

const booleanas = new Set(j.columns.filter((c) => tipoPg(c) === 'boolean').map((c) => `${c.t}.${c.c}`));

function defaultPg(c, tipo) {
	if (c.def === null) return null;
	if (/^CURRENT_TIMESTAMP/.test(c.def)) return 'CURRENT_TIMESTAMP';
	if (tipo === 'boolean') return c.def === '1' ? 'true' : 'false';
	if (esTexto(c)) return lit(c.def);
	return c.def;
}

// Las 22 expresiones generadas de MySQL, traducidas una por una. Una nueva rompe la generacion a
// proposito: no se adivina.
function generadaPg(c, tipo) {
	const e = c.gen.replace(/`/g, '').replace(/_utf8mb4\\'/g, "'").replace(/\\'/g, "'");
	const epoca = tipo.startsWith('timestamptz') ? "'1970-01-01 00:00:00+00'::timestamptz" : "'1970-01-01 00:00:00'::timestamp";
	let m;
	if ((m = e.match(/^ifnull\((\w+),'1970-01-01 00:00:00(?:\.000000)?'\)$/))) return `COALESCE(${m[1]}, ${epoca})`;
	if ((m = e.match(/^ifnull\((\w+),0\)$/))) return `COALESCE(${m[1]}, 0)`;
	const json = (k) => `details ->> '${k}'`;
	const tabla = {
		"left(coalesce(json_unquote(json_extract(details,'$.profesionalMembershipId')),json_unquote(json_extract(details,'$.membershipId'))),32)":
			`left(COALESCE(${json('profesionalMembershipId')}, ${json('membershipId')}), 32)`,
		"left(json_unquote(json_extract(details,'$.profesionalAnteriorId')),32)": `left(${json('profesionalAnteriorId')}, 32)`,
		"left(json_unquote(json_extract(details,'$.turnoOrigenId')),32)": `left(${json('turnoOrigenId')}, 32)`,
		"if((estado = 'PENDIENTE'),nombre_propuesto,NULL)": "CASE WHEN estado = 'PENDIENTE' THEN nombre_propuesto END",
		'(case when (deleted_at is null) then turno_id end)': 'CASE WHEN deleted_at IS NULL THEN turno_id END',
		"if((estado = 'ABIERTA'),1,NULL)": "CASE WHEN estado = 'ABIERTA' THEN 1 END",
		'if(((0 <> activo) and (reemplaza_libro_id is null)),hash_sha256,NULL)': 'CASE WHEN activo AND reemplaza_libro_id IS NULL THEN hash_sha256 END',
		'if((active = 1),permission_code,NULL)': 'CASE WHEN active THEN permission_code END',
		"(medio = 'EFECTIVO')": "CASE WHEN medio = 'EFECTIVO' THEN 1 ELSE 0 END",
		"(case when ((estado <> 'ANULADA') and (deleted_at is null)) then asistencia_id end)": "CASE WHEN estado <> 'ANULADA' AND deleted_at IS NULL THEN asistencia_id END",
		'(case when ((principal = 1) and (deleted_at is null)) then 1 end)': 'CASE WHEN principal AND deleted_at IS NULL THEN 1 END',
		"if((estado in ('ACTIVO','SUSPENDIDO')),0,numero_plan)": "CASE WHEN estado IN ('ACTIVO', 'SUSPENDIDO') THEN 0 ELSE numero_plan END",
		'if((active = 1),role_code,NULL)': 'CASE WHEN active THEN role_code END',
		"if((estado in ('INCLUIDO','ACEPTADO','DEBITADO_PARCIAL')),1,NULL)": "CASE WHEN estado IN ('INCLUIDO', 'ACEPTADO', 'DEBITADO_PARCIAL') THEN 1 END",
		"(case when (estado <> 'ANULADA') then turno_id end)": "CASE WHEN estado <> 'ANULADA' THEN turno_id END",
	};
	if (tabla[e]) return tabla[e];
	throw new Error(`expresion generada sin traducir ${c.t}.${c.c}: ${e}`);
}

function checkPg(t, clausula) {
	let s = clausula.replace(/`/g, '').replace(/_utf8mb4\\'/g, "'").replace(/\\'/g, "'");
	// Booleanos: MySQL los compara con 0/1; PostgreSQL no compara boolean con integer.
	s = s.replace(/\((\w+) = ([01])\)/g, (m, col, v) => booleanas.has(`${t}.${col}`) ? `(${col} = ${v === '1'})` : m);
	// Los regex no admiten una collation no determinista: se comparan en "C".
	s = s.replace(/regexp_like\((\w+),('[^']*')\)/g, '(($1 COLLATE "C") ~ $2)');
	if (/regexp_like|json_|ifnull|\bif\(/.test(s)) throw new Error(`check sin traducir ${t}: ${s}`);
	return s;
}

// ---------------------------------------------------------------- constraints e indices
const cons = porTabla(j.cons);
const kcu = {};
for (const k of j.kcu) (kcu[`${k.t}.${k.n}`] ||= []).push(k);
for (const k in kcu) kcu[k].sort((a, b) => a.pos - b.pos);
const refs = Object.fromEntries((j.refs || []).map((r) => [`${r.t}.${r.n}`, r]));
const checks = porTabla(j.checks);
const stats = {};
for (const s of j.stats) ((stats[s.t] ||= {})[s.i] ||= []).push(s);

// Nombres de indice y de constraint con indice: en PostgreSQL son unicos por esquema, en MySQL los
// indices son por tabla.
const usados = new Map();
function nombreUnico(t, n) {
	const base = n.length > 63 ? n.slice(0, 63) : n;
	if (!usados.has(base)) { usados.set(base, t); return base; }
	const otro = `${t}_${n}`.slice(0, 63);
	if (usados.has(otro)) throw new Error(`nombre repetido ${otro}`);
	usados.set(otro, t);
	return otro;
}

const ordenModulos = [
	['V2__platform_auditoria', ['platform']],
	['V3__organizacion_identidad_y_notificaciones', ['organization', 'identity', 'notification']],
	['V4__recursos_y_ofertas', ['resource', 'offering']],
	['V5__personas_y_contratacion', ['person', 'contracting']],
	['V6__agenda_y_turnos', ['scheduling']],
	['V7__clinica_y_atencion', ['clinical', 'encounter']],
	['V8__economia', ['billing']],
	['V9__actividades_y_clases', ['activity']],
	['V10__biblioteca', ['knowledge']],
];

const fks = [];
const tocaUpdatedAt = [];
const cabecera = (titulo) => `-- =====================================================================================
-- AKINE — ${titulo}
--
-- Baseline PostgreSQL consolidado (11/11/2026). Reemplaza las 145 migraciones de MySQL, que quedan
-- como archivo historico en ops/migracion-mysql/mysql-historico. Generado por
-- ops/migracion-mysql/generar-baseline.mjs desde el esquema final de MySQL y revisado a mano.
--
-- Convenciones que vienen de MySQL y se conservan:
--   * Textos con COLLATE akine_ci: comparacion sin mayusculas ni tildes, como utf8mb4_0900_ai_ci.
--   * Instantes en timestamptz (UTC); fechas en date; horas de agenda en time.
--   * Las claves *_key generadas sostienen los UNIQUE de la baja logica (centinela 1970-01-01).
--   * Las claves foraneas se crean todas juntas en V11, despues de todas las tablas.
-- =====================================================================================
`;

for (const [archivo, mods] of ordenModulos) {
	const tablas = Object.keys(columnas).filter((t) => mods.includes(modulo[t])).sort();
	let sql = cabecera(`${mods.join(', ')}`);
	for (const t of tablas) {
		const lineas = [];
		const comentarios = [];
		for (const c of columnas[t]) {
			const tipo = tipoPg(c);
			let l = `    ${c.c} ${tipo}`;
			if (esTexto(c) && c.coll) l += ' COLLATE akine_ci';
			if (c.gen) {
				l += ` GENERATED ALWAYS AS (${generadaPg(c, tipo)}) STORED`;
			} else {
				if (c.extra.includes('auto_increment')) l += ' GENERATED BY DEFAULT AS IDENTITY';
				const d = defaultPg(c, tipo);
				if (d !== null) l += ` DEFAULT ${d}`;
				if (c.null === 'NO') l += ' NOT NULL';
			}
			if (c.extra.includes('on update')) {
				if (c.c !== 'updated_at') throw new Error(`ON UPDATE fuera de updated_at: ${t}.${c.c}`);
				tocaUpdatedAt.push([t, c.c]);
			}
			lineas.push(l);
			const comentario = t === 'libro_fragmento' && c.c === 'vector'
				? 'Embedding de multilingual-e5-base (768 dimensiones). NULL hasta que el worker lo calcula. Invariante: vector IS NULL <=> modelo_embeddings IS NULL'
				: c.comment;
			if (comentario) comentarios.push(`COMMENT ON COLUMN ${t}.${c.c} IS ${lit(comentario)};`);
		}
		for (const k of cons[t] || []) {
			const cols = (kcu[`${t}.${k.n}`] || []).map((x) => x.c).join(', ');
			if (k.type === 'PRIMARY KEY') lineas.push(`    CONSTRAINT ${nombreUnico(t, `pk_${t}`)} PRIMARY KEY (${cols})`);
			else if (k.type === 'UNIQUE') lineas.push(`    CONSTRAINT ${nombreUnico(t, k.n)} UNIQUE (${cols})`);
			else if (k.type === 'FOREIGN KEY') {
				const ks = kcu[`${t}.${k.n}`];
				const r = refs[`${t}.${k.n}`];
				let f = `ALTER TABLE ${t} ADD CONSTRAINT ${k.n} FOREIGN KEY (${cols}) REFERENCES ${ks[0].rt} (${ks.map((x) => x.rc).join(', ')})`;
				if (r.del === 'CASCADE' || r.del === 'SET NULL') f += ` ON DELETE ${r.del}`;
				if (r.upd === 'CASCADE' || r.upd === 'SET NULL') f += ` ON UPDATE ${r.upd}`;
				fks.push([modulo[t], `${f};`]);
			}
		}
		for (const k of checks[t] || []) lineas.push(`    CONSTRAINT ${k.n} CHECK ${checkPg(t, k.clause)}`);
		sql += `\nCREATE TABLE ${t}\n(\n${lineas.join(',\n')}\n);\n`;
		const conIndice = new Set((cons[t] || []).filter((k) => k.type !== 'CHECK' && k.type !== 'FOREIGN KEY').map((k) => k.n));
		for (const [i, partes] of Object.entries(stats[t] || {})) {
			if (conIndice.has(i) || partes[0].type === 'FULLTEXT') continue;
			partes.sort((a, b) => a.seq - b.seq);
			sql += `CREATE INDEX ${nombreUnico(t, i)} ON ${t} (${partes.map((p) => p.c).join(', ')});\n`;
		}
		if (comentarioTabla[t]) sql += `COMMENT ON TABLE ${t} IS ${lit(comentarioTabla[t])};\n`;
		if (comentarios.length) sql += comentarios.join('\n') + '\n';
	}
	fs.writeFileSync(path.join(salida, `${archivo}.sql`), sql);
}

// ---------------------------------------------------------------- claves foraneas
let sqlFk = cabecera('claves foraneas de todos los modulos');
for (const [, mods] of ordenModulos) {
	for (const m of mods) {
		const propias = fks.filter((f) => f[0] === m).map((f) => f[1]);
		if (propias.length) sqlFk += `\n-- ${m}\n${propias.join('\n')}\n`;
	}
}
fs.writeFileSync(path.join(salida, 'V11__claves_foraneas.sql'), sqlFk);

// ---------------------------------------------------------------- updated_at
let sqlUpd = cabecera('updated_at automatico (equivalente de ON UPDATE CURRENT_TIMESTAMP)');
for (const [t, c] of tocaUpdatedAt) {
	sqlUpd += `\nCREATE TRIGGER trg_${t}_${c}_al_modificar BEFORE UPDATE ON ${t}\n    FOR EACH ROW EXECUTE FUNCTION akine_marcar_updated_at();\n`;
}
fs.writeFileSync(path.join(salida, 'V12__marcas_de_modificacion.sql'), sqlUpd);

console.log(`tablas ${Object.keys(columnas).length}, fks ${fks.length}, updated_at ${tocaUpdatedAt.length}, nombres ${usados.size}`);

// ---------------------------------------------------------------- biblioteca: texto y vector
fs.appendFileSync(path.join(salida, 'V10__biblioteca.sql'), `
-- -------------------------------------------------------------------------------------
-- Busqueda de la biblioteca en PostgreSQL (reemplaza el FULLTEXT de MySQL y el recorrido en memoria).
--
-- Texto: los libros son en espanol y en ingles y el libro no declara idioma, asi que cada fragmento
-- se indexa con las dos configuraciones y la consulta se arma con las dos. Las dos ignoran tildes
-- (unaccent), como el FULLTEXT de MySQL con utf8mb4_0900_ai_ci, y reducen cada palabra a su raiz:
-- "rodillas" encuentra "rodilla". Terminos anatomicos y tecnicos que el diccionario no conoce
-- quedan como estan, sin raiz, y se encuentran por igualdad.
--
-- Vector: 768 dimensiones, las de multilingual-e5-base (verificadas en el modelo ONNX instalado).
-- Los puntajes son coseno, igual que el recorrido en Java que reemplaza. El indice HNSW es
-- aproximado; la consulta lo usa con recorrido iterativo para no perder filas por el filtro de
-- organizacion y estado (ver PgAlmacenVectorial).
-- -------------------------------------------------------------------------------------
CREATE TEXT SEARCH CONFIGURATION akine_es (COPY = pg_catalog.spanish);
ALTER TEXT SEARCH CONFIGURATION akine_es
    ALTER MAPPING FOR hword, hword_part, word WITH unaccent, spanish_stem;

CREATE TEXT SEARCH CONFIGURATION akine_en (COPY = pg_catalog.english);
ALTER TEXT SEARCH CONFIGURATION akine_en
    ALTER MAPPING FOR hword, hword_part, word WITH unaccent, english_stem;

ALTER TABLE libro_fragmento
    ADD COLUMN texto_tsv tsvector GENERATED ALWAYS AS (
        to_tsvector('akine_es'::regconfig, texto) || to_tsvector('akine_en'::regconfig, texto)) STORED;
COMMENT ON COLUMN libro_fragmento.texto_tsv IS 'Texto indexado en espanol e ingles, sin tildes. Lo calcula la base';

CREATE INDEX ix_libro_fragmento_texto_tsv ON libro_fragmento USING gin (texto_tsv);
CREATE INDEX ix_libro_fragmento_vector ON libro_fragmento USING hnsw (vector vector_cosine_ops);
`);

// ---------------------------------------------------------------- auditoria append-only
fs.appendFileSync(path.join(salida, 'V12__marcas_de_modificacion.sql'), `
-- audit_event es append-only en la base (RN-M24-001): los dos triggers que tenia MySQL.
CREATE TRIGGER trg_audit_event_no_update BEFORE UPDATE ON audit_event
    FOR EACH ROW EXECUTE FUNCTION akine_auditoria_append_only();
CREATE TRIGGER trg_audit_event_no_delete BEFORE DELETE ON audit_event
    FOR EACH ROW EXECUTE FUNCTION akine_auditoria_append_only();
`);

// ---------------------------------------------------------------- datos iniciales
const semillas = leer('seeds.jsonl').trim().split('\n').map((l) => JSON.parse(l));
const ordenSemillas = ['platform_schema_info', 'plan', 'plan_feature', 'plan_limit', 'cuenta', 'platform_role', 'especialidad', 'practica', 'feriado'];
let sqlSem = cabecera('datos iniciales: planes, cuenta de plataforma, catalogos globales y feriados') +
	`--
-- Son las filas que sembraban las migraciones de MySQL (V5, V10, V15, V18, V19, V21 y siguientes),
-- con sus mismos identificadores. Las fechas de alta toman el instante de la migracion, como alla.
`;
for (const t of ordenSemillas) {
	const s = semillas.find((x) => x.t === t);
	if (!s?.rows?.length) continue;
	const cols = columnas[t].filter((c) => !c.gen);
	const valor = (c, v) => {
		if (v === null || v === undefined) return 'NULL';
		const tipo = tipoPg(c);
		if (tipo === 'boolean') return v ? 'true' : 'false';
		if (tipo.startsWith('timestamp') && /^2026-11-12 0[0-9]:/.test(v)) return 'CURRENT_TIMESTAMP';
		if (tipo.startsWith('timestamptz')) return `${lit(v)}::timestamptz`;
		if (typeof v === 'number') return String(v);
		if (typeof v === 'object') return `${lit(JSON.stringify(v))}::jsonb`;
		return lit(v);
	};
	sqlSem += `\nINSERT INTO ${t} (${cols.map((c) => c.c).join(', ')}) VALUES\n` +
		s.rows.map((r) => `    (${cols.map((c) => valor(c, r[c.c])).join(', ')})`).join(',\n') + ';\n';
	if (cols.some((c) => c.extra.includes('auto_increment'))) {
		sqlSem += `SELECT setval(pg_get_serial_sequence('${t}', 'id'), (SELECT MAX(id) FROM ${t}));\n`;
	}
}
fs.writeFileSync(path.join(salida, 'V13__datos_iniciales.sql'), sqlSem);
