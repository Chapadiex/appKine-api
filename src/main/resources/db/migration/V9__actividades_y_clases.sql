CREATE TABLE asistencia_actividad
(
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    organization_id bigint NOT NULL,
    consultorio_id bigint NOT NULL,
    clase_id bigint NOT NULL,
    persona_id bigint NOT NULL,
    inscripcion_id bigint NOT NULL,
    resultado varchar(16) COLLATE akine_ci NOT NULL,
    origen varchar(24) COLLATE akine_ci NOT NULL,
    profesional_membership_id bigint,
    observaciones varchar(500) COLLATE akine_ci,
    registrada_en timestamptz(6) NOT NULL,
    registrada_por_cuenta_id bigint NOT NULL,
    corregida_en timestamptz(6),
    corregida_por_cuenta_id bigint,
    correcciones integer DEFAULT 0 NOT NULL,
    created_at timestamptz(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at timestamptz(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    version bigint DEFAULT 0 NOT NULL,
    CONSTRAINT pk_asistencia_actividad PRIMARY KEY (id),
