CREATE TABLE turno
(
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    organization_id bigint NOT NULL,
    consultorio_id bigint NOT NULL,
    oferta_id bigint NOT NULL,
    persona_id bigint NOT NULL,
    serie_id bigint,
    cobertura_id bigint,
    caso_id bigint,
    plan_id bigint,
    origen varchar(16) COLLATE akine_ci,
    sobreturno boolean DEFAULT false NOT NULL,
    sobreturno_motivo varchar(300) COLLATE akine_ci,
    sobreturno_autorizado_por_cuenta_id bigint,
    observaciones varchar(500) COLLATE akine_ci,
    turno_origen_id bigint,
    profesional_membership_id bigint,
    espacio_id bigint,
    inicio timestamptz(6) NOT NULL,
    fin timestamptz(6) NOT NULL,
    estado varchar(16) COLLATE akine_ci NOT NULL,
    motivo_cancelacion varchar(300) COLLATE akine_ci,
    cancelado_en timestamptz(6),
    cancelado_por_cuenta_id bigint,
    origen_cancelacion varchar(16) COLLATE akine_ci,
    ausente_en timestamptz(6),
    ausencia_consume_sesion boolean,
    reprogramado_en timestamptz(6),
    llegada_en timestamptz(6),
    llegada_por_cuenta_id bigint,
    estado_antes_de_espera varchar(16) COLLATE akine_ci,
    idempotency_key varchar(80) COLLATE akine_ci,
    request_hash varchar(64) COLLATE akine_ci,
    reservado_por_cuenta_id bigint NOT NULL,
    reservado_en timestamptz(6) NOT NULL,
    confirmado_en timestamptz(6),
    created_at timestamptz(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at timestamptz(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    deleted_at timestamptz(6),
    deleted_key timestamptz(6) GENERATED ALWAYS AS (COALESCE(deleted_at, '1970-01-01 00:00:00+00'::timestamptz)) STORED,
    version bigint DEFAULT 0 NOT NULL,
    CONSTRAINT pk_turno PRIMARY KEY (id),
    CONSTRAINT uk_turno_idempotencia UNIQUE (organization_id, idempotency_key),
    CONSTRAINT ck_turno_cancelacion_completa CHECK (((cancelado_en is null) and (motivo_cancelacion is null) and (cancelado_por_cuenta_id is null)) or ((cancelado_en is not null) and (motivo_cancelacion is not null) and (cancelado_por_cuenta_id is not null))),
    CONSTRAINT ck_turno_estado CHECK (estado in ('RESERVADO','CONFIRMADO','CANCELADO','AUSENTE')),
    CONSTRAINT ck_turno_idempotencia_completa CHECK (((idempotency_key is null) and (request_hash is null)) or ((idempotency_key is not null) and (request_hash is not null))),
    CONSTRAINT ck_turno_intervalo CHECK (fin > inicio),
    CONSTRAINT ck_turno_llegada_con_responsable CHECK (((llegada_en is null) and (llegada_por_cuenta_id is null)) or ((llegada_en is not null) and (llegada_por_cuenta_id is not null))),
    CONSTRAINT ck_turno_origen_cancelacion CHECK ((origen_cancelacion is null) or (origen_cancelacion in ('PACIENTE','PROFESIONAL','INSTITUCION'))),
    CONSTRAINT ck_turno_sobreturno_completo CHECK (((sobreturno = false) and (sobreturno_motivo is null) and (sobreturno_autorizado_por_cuenta_id is null)) or ((sobreturno = true) and (sobreturno_motivo is not null) and (sobreturno_autorizado_por_cuenta_id is not null)))
);
CREATE INDEX fk_turno_consultorio ON turno (consultorio_id);
CREATE INDEX fk_turno_espacio ON turno (espacio_id);
CREATE INDEX fk_turno_oferta ON turno (oferta_id);
CREATE INDEX fk_turno_persona ON turno (persona_id);
CREATE INDEX fk_turno_turno_origen ON turno (turno_origen_id);
CREATE INDEX fk_turno_turno_serie ON turno (serie_id);
CREATE INDEX ix_turno_espacio_intervalo ON turno (organization_id, espacio_id, deleted_key, inicio, fin);
CREATE INDEX ix_turno_oferta_inicio ON turno (organization_id, oferta_id, inicio, deleted_key);
CREATE INDEX ix_turno_persona ON turno (organization_id, persona_id, inicio);
CREATE INDEX ix_turno_plan ON turno (organization_id, plan_id);
CREATE INDEX ix_turno_profesional_intervalo ON turno (organization_id, profesional_membership_id, deleted_key, inicio, fin);
CREATE INDEX ix_turno_sede_dia ON turno (organization_id, consultorio_id, inicio);
CREATE INDEX ix_turno_serie_inicio ON turno (organization_id, serie_id, inicio);
CREATE INDEX ix_turno_turno_origen ON turno (organization_id, turno_origen_id);
COMMENT ON TABLE turno IS 'Reserva de un slot. No es la prestacion: DP-05 separa Turno, Recepcion y Sesion.';
COMMENT ON COLUMN turno.persona_id IS 'Identidad del paciente. Ver el punto 5 de la cabecera.';
