COMMENT ON COLUMN turno.estado_antes_de_espera IS 'De donde vino el check-in, para poder deshacerlo sin inventar una confirmacion.';
COMMENT ON COLUMN turno.request_hash IS 'SHA-256 del pedido. Ver el punto 4.';

