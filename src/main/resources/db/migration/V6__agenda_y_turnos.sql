-- =====================================================================================
-- AKINE — scheduling
--
-- Baseline PostgreSQL consolidado (11/11/2026). Reemplaza las 145 migraciones de MySQL, que quedan
-- como archivo historico en ops/migracion-mysql/mysql-historico. Generado por
-- ops/migracion-mysql/generar-baseline.mjs desde el esquema final de MySQL y revisado a mano.
--
-- Convenciones que vienen de MySQL y se conservan:
--   * Textos con COLLATE akine_ci: comparacion sin mayusculas ni tildes, como utf8mb4_0900_ai_ci.
--   * Instantes en timestamptz (UTC); fechas en date; horas de agenda en time.
--   * Las claves *_key generadas sostienen los UNIQUE de la baja logica (centinela 1970-01-01).
--   * Las claves foraneas se crean todas juntas en V11, despues de todas las tablas.
-- =====================================================================================

CREATE TABLE agenda_sede
(
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    organization_id bigint NOT NULL,
    consultorio_id bigint NOT NULL,
    created_at timestamptz(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_agenda_sede PRIMARY KEY (id),
    CONSTRAINT uk_agenda_sede UNIQUE (organization_id, consultorio_id)
);
CREATE INDEX fk_agenda_sede_consultorio ON agenda_sede (consultorio_id);
COMMENT ON TABLE agenda_sede IS 'Fila por sede que sirve unicamente para serializar las reservas con FOR UPDATE. No guarda estado.';

CREATE TABLE lista_espera_turno
(
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    organization_id bigint NOT NULL,
    consultorio_id bigint NOT NULL,
    persona_id bigint NOT NULL,
    oferta_id bigint NOT NULL,
    profesional_membership_id bigint,
    caso_id bigint,
    plan_id bigint,
    fecha_desde date NOT NULL,
    fecha_hasta date NOT NULL,
    dias_semana varchar(13) COLLATE akine_ci,
    hora_desde time,
    hora_hasta time,
    prioridad varchar(8) COLLATE akine_ci DEFAULT 'NORMAL' NOT NULL,
    notas varchar(300) COLLATE akine_ci,
    estado varchar(12) COLLATE akine_ci DEFAULT 'ACTIVA' NOT NULL,
    turno_id bigint,
    motivo_cierre varchar(300) COLLATE akine_ci,
    creada_por_cuenta_id bigint NOT NULL,
    creada_en timestamptz(6) NOT NULL,
    cerrada_por_cuenta_id bigint,
    cerrada_en timestamptz(6),
    version bigint DEFAULT 0 NOT NULL,
    CONSTRAINT pk_lista_espera_turno PRIMARY KEY (id),
    CONSTRAINT ck_lista_espera_turno_asignada CHECK ((estado <> 'ASIGNADA') or (turno_id is not null)),
    CONSTRAINT ck_lista_espera_turno_estado CHECK (estado in ('ACTIVA','ASIGNADA','DESCARTADA')),
    CONSTRAINT ck_lista_espera_turno_fechas CHECK (fecha_hasta >= fecha_desde),
    CONSTRAINT ck_lista_espera_turno_franja CHECK (((hora_desde is null) and (hora_hasta is null)) or ((hora_desde is not null) and (hora_hasta is not null) and (hora_hasta > hora_desde))),
    CONSTRAINT ck_lista_espera_turno_prioridad CHECK (prioridad in ('NORMAL','ALTA','URGENTE'))
);
CREATE INDEX fk_lista_espera_turno_consultorio ON lista_espera_turno (consultorio_id);
CREATE INDEX fk_lista_espera_turno_turno ON lista_espera_turno (turno_id);
CREATE INDEX ix_lista_espera_turno_persona ON lista_espera_turno (organization_id, persona_id);
CREATE INDEX ix_lista_espera_turno_sede ON lista_espera_turno (organization_id, consultorio_id, estado, oferta_id);
COMMENT ON TABLE lista_espera_turno IS 'Pacientes que esperan un lugar de una prestacion. Propiedad de scheduling';
COMMENT ON COLUMN lista_espera_turno.persona_id IS 'Persona del padron con perfil de paciente vigente al anotarse';
COMMENT ON COLUMN lista_espera_turno.oferta_id IS 'Prestacion que espera';
COMMENT ON COLUMN lista_espera_turno.profesional_membership_id IS 'Profesional preferido. NULL = cualquiera habilitado';
COMMENT ON COLUMN lista_espera_turno.caso_id IS 'Caso clinico asociado, sin FK: es de clinical';
COMMENT ON COLUMN lista_espera_turno.plan_id IS 'Plan asociado, sin FK: es de clinical';
COMMENT ON COLUMN lista_espera_turno.fecha_desde IS 'Primer dia que le sirve, en la zona de la sede';
COMMENT ON COLUMN lista_espera_turno.fecha_hasta IS 'Ultimo dia que le sirve, INCLUSIVO';
COMMENT ON COLUMN lista_espera_turno.dias_semana IS 'Dias posibles, ISO separados por coma (1,3,5). NULL = cualquiera';
COMMENT ON COLUMN lista_espera_turno.hora_desde IS 'Franja horaria local. NULL = cualquiera';
COMMENT ON COLUMN lista_espera_turno.hora_hasta IS 'Fin de la franja, EXCLUSIVO';
COMMENT ON COLUMN lista_espera_turno.prioridad IS 'NORMAL, ALTA o URGENTE';
COMMENT ON COLUMN lista_espera_turno.notas IS 'Preferencias operativas. NUNCA informacion clinica';
COMMENT ON COLUMN lista_espera_turno.estado IS 'ACTIVA, ASIGNADA o DESCARTADA';
COMMENT ON COLUMN lista_espera_turno.turno_id IS 'Turno que se le asigno';
COMMENT ON COLUMN lista_espera_turno.motivo_cierre IS 'Por que se descarto';

CREATE TABLE recepcion
(
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    organization_id bigint NOT NULL,
    consultorio_id bigint NOT NULL,
    turno_id bigint NOT NULL,
    estado varchar(16) COLLATE akine_ci NOT NULL,
    llegada_en timestamptz(6) NOT NULL,
    llegada_por_cuenta_id bigint NOT NULL,
    modalidad varchar(16) COLLATE akine_ci,
    practica_id bigint,
    cobertura_id bigint,
    convenio_id bigint,
    observacion varchar(1000) COLLATE akine_ci,
    motivo_particular varchar(300) COLLATE akine_ci,
    validada_en timestamptz(6),
    validada_por_cuenta_id bigint,
    en_espera_desde timestamptz(6),
    llamada_en timestamptz(6),
    llamada_por_cuenta_id bigint,
    cerrada_en timestamptz(6),
    cerrada_por_cuenta_id bigint,
    motivo_cierre varchar(300) COLLATE akine_ci,
    turno_vigente_id bigint GENERATED ALWAYS AS (CASE WHEN estado <> 'ANULADA' THEN turno_id END) STORED,
    created_at timestamptz(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at timestamptz(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    version bigint DEFAULT 0 NOT NULL,
    CONSTRAINT pk_recepcion PRIMARY KEY (id),
    CONSTRAINT uk_recepcion_turno_vigente UNIQUE (organization_id, turno_vigente_id),
    CONSTRAINT ck_recepcion_cierre CHECK ((estado in ('ANULADA','CERRADA','RETIRADO')) = (cerrada_en is not null)),
    CONSTRAINT ck_recepcion_estado CHECK (estado in ('LLEGO','VALIDADA','OBSERVADA','EN_ESPERA','LLAMADA','ANULADA','CERRADA','RETIRADO')),
    CONSTRAINT ck_recepcion_llamada CHECK ((estado <> 'LLAMADA') or (llamada_en is not null)),
    CONSTRAINT ck_recepcion_modalidad CHECK ((modalidad is null) or (modalidad in ('COBERTURA','PARTICULAR'))),
    CONSTRAINT ck_recepcion_observada_con_observacion CHECK ((estado <> 'OBSERVADA') or (observacion is not null)),
    CONSTRAINT ck_recepcion_particular_con_motivo CHECK ((modalidad is null) or (modalidad <> 'PARTICULAR') or (motivo_particular is not null)),
    CONSTRAINT ck_recepcion_retirado_con_motivo CHECK ((estado <> 'RETIRADO') or (motivo_cierre is not null)),
    CONSTRAINT ck_recepcion_validada_con_modalidad CHECK ((estado <> 'VALIDADA') or (modalidad is not null))
);
CREATE INDEX fk_recepcion_consultorio ON recepcion (consultorio_id);
CREATE INDEX fk_recepcion_turno ON recepcion (turno_id);
CREATE INDEX ix_recepcion_turno ON recepcion (organization_id, turno_id);
COMMENT ON TABLE recepcion IS 'Recepcion de un turno (M13, DP-16): llegada, validacion administrativa, espera y llamado. No prueba que una prestacion ocurrio (DP-05).';
COMMENT ON COLUMN recepcion.llegada_en IS 'Hora real de llegada, puesta por el servidor.';
COMMENT ON COLUMN recepcion.llegada_por_cuenta_id IS 'Quien registro la llegada: siempre hay un responsable.';
COMMENT ON COLUMN recepcion.modalidad IS 'COBERTURA o PARTICULAR. NULL = sin resolver.';
COMMENT ON COLUMN recepcion.practica_id IS 'Practica con la que se valido (principal de la oferta, DP-11).';
COMMENT ON COLUMN recepcion.cobertura_id IS 'Cobertura del paciente con la que se valido.';
COMMENT ON COLUMN recepcion.convenio_id IS 'Convenio vigente que fijo los requisitos.';
COMMENT ON COLUMN recepcion.observacion IS 'Lo que la validacion observo. Advierte, no bloquea (RN-M13-003).';
COMMENT ON COLUMN recepcion.motivo_particular IS 'Por que el operador decidio atender como Particular (RF-M13-005).';
COMMENT ON COLUMN recepcion.cerrada_en IS 'Hora de ANULADA o CERRADA.';

