COMMENT ON COLUMN turno.origen IS 'Desde donde se inicio la reserva. Solo trazabilidad: no cambia ninguna regla';
COMMENT ON COLUMN turno.sobreturno IS '1 si se reservo sobre un horario ocupado, con autorizacion';
