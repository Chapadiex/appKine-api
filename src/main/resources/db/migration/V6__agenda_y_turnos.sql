COMMENT ON COLUMN turno.estado IS 'RESERVADO o CONFIRMADO en esta etapa. El resto del ciclo llega en 05.03.';
COMMENT ON COLUMN turno.origen_cancelacion IS 'Quien cancelo: PACIENTE, PROFESIONAL o INSTITUCION. NULL en cancelaciones anteriores a V125';
COMMENT ON COLUMN turno.ausencia_consume_sesion IS 'Si la ausencia consume una sesion del plan. NULL si no se decidio o el turno no tiene plan';
COMMENT ON COLUMN turno.llegada_en IS 'Hora real de llegada, puesta por el servidor. NULL mientras el paciente no llego.';
