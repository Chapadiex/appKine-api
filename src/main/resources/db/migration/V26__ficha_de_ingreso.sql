-- Ficha de ingreso del paciente (extiende DP-47, docs/diseno/AKINE-ficha-de-ingreso.md).
--
-- Tres cambios: el catalogo de ocupaciones (global sembrado + propio de cada centro, patron
-- owner_key de ADR-0021), la ficha de la historia (una fila por HC, mismo circuito de origen y
-- revision que V16) y cuatro columnas opcionales del antecedente para cirugias y enfermedades.
-- Los nombres de constraint llevan la tabla adelante: en PostgreSQL son unicos por esquema.

CREATE TABLE ocupacion
(
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    organization_id bigint,
    owner_key bigint GENERATED ALWAYS AS (COALESCE(organization_id, 0)) STORED,
    nombre varchar(80) COLLATE akine_ci NOT NULL,
    nombre_normalizado varchar(80) NOT NULL,
    active boolean DEFAULT true NOT NULL,
    created_at timestamptz(6) NOT NULL,
    CONSTRAINT pk_ocupacion PRIMARY KEY (id),
    CONSTRAINT fk_ocupacion_organization FOREIGN KEY (organization_id) REFERENCES organization (id),
    CONSTRAINT uk_ocupacion_nombre UNIQUE (owner_key, nombre_normalizado),
    CONSTRAINT ck_ocupacion_nombre CHECK (length(btrim(nombre)) > 0)
);
CREATE INDEX ix_ocupacion_owner ON ocupacion (owner_key, active, nombre);
COMMENT ON TABLE ocupacion IS 'Ocupaciones u oficios para la ficha de ingreso. Filas globales (organization_id NULL) sembradas por el producto y filas propias de cada centro. Toda lectura filtra por owner_key IN (0, org). Propietario: modulo clinical';
COMMENT ON COLUMN ocupacion.nombre_normalizado IS 'Minusculas, sin tildes y con espacios colapsados: "Docente" y " dócente " no se duplican dentro del mismo dueño';

