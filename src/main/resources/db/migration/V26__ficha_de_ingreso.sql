CREATE TABLE historia_clinica_ficha
(
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    organization_id bigint NOT NULL,
    historia_clinica_id bigint NOT NULL,
    ocupacion_id bigint,
    peso_kg numeric(5, 1),
    altura_cm numeric(5, 1),
    actividad_fisica varchar(16),
    actividad_detalle varchar(120) COLLATE akine_ci,
    origen varchar(16) NOT NULL,
    cargado_por bigint NOT NULL,
    revisado_por bigint,
    revisado_en timestamptz(6),
    version bigint DEFAULT 0 NOT NULL,
    created_at timestamptz(6) NOT NULL,
    updated_at timestamptz(6) NOT NULL,
    CONSTRAINT pk_historia_clinica_ficha PRIMARY KEY (id),
    CONSTRAINT fk_hc_ficha_organization FOREIGN KEY (organization_id) REFERENCES organization (id),
    CONSTRAINT fk_hc_ficha_historia FOREIGN KEY (historia_clinica_id) REFERENCES historia_clinica (id),
    CONSTRAINT fk_hc_ficha_ocupacion FOREIGN KEY (ocupacion_id) REFERENCES ocupacion (id),
    CONSTRAINT uk_hc_ficha_historia UNIQUE (organization_id, historia_clinica_id),
    CONSTRAINT ck_hc_ficha_peso CHECK (peso_kg IS NULL OR peso_kg BETWEEN 1 AND 400),
    CONSTRAINT ck_hc_ficha_altura CHECK (altura_cm IS NULL OR altura_cm BETWEEN 30 AND 250),
    CONSTRAINT ck_hc_ficha_actividad
        CHECK (actividad_fisica IS NULL OR actividad_fisica IN ('SEDENTARIO', 'OCASIONAL', 'REGULAR', 'DEPORTISTA')),
    CONSTRAINT ck_hc_ficha_origen CHECK (origen IN ('PROFESIONAL', 'DECLARADO')),
    CONSTRAINT ck_hc_ficha_revision_coherente CHECK ((revisado_por IS NULL) = (revisado_en IS NULL))
);
CREATE INDEX fk_hc_ficha_ocupacion ON historia_clinica_ficha (ocupacion_id);
COMMENT ON TABLE historia_clinica_ficha IS 'Ficha de ingreso: ocupacion, peso, altura y actividad fisica de la historia. Una fila por HC; el IMC se calcula al leer. Lo que carga quien declara queda sin revisar; lo que carga un profesional queda revisado por el. Propietario: modulo clinical';

