-- =====================================================================================
-- AKINE — Carga por Telegram (docs/diseno/AKINE-telegram.md).
--
-- Cada centro conecta su propio bot (lo crea en @BotFather y pega el token en AKINE). El
-- backend le pregunta a Telegram por los mensajes nuevos (polling, sin URL publica) y cada
-- mensaje de un profesional vinculado entra al asistente con los permisos de su cuenta.
--
-- telegram_bot: uno por organizacion. El token va cifrado (AES-GCM, clave del despliegue) y se
-- borra al desconectar; la fila queda con activo = false. ultimo_update_id es el offset de
-- getUpdates: Telegram no reenvia lo que ya se confirmo. tomado_hasta es el alquiler del
-- sondeo: con dos instancias, una sola pregunta por bot a la vez (Telegram responde 409 si
-- dos getUpdates del mismo bot se cruzan).
--
-- telegram_vinculo: una cuenta de la organizacion con su usuario de Telegram. Se crea con un
-- codigo de un solo uso que la persona manda al bot como "/vincular CODIGO". El codigo lleva la
-- sede desde la que se pidio (codigo_consultorio_id), que pasa a consultorio_id recien al usarse:
-- pedir un codigo en otra sede no mueve la carga hasta confirmarlo desde Telegram. Desvincular
-- deja la fila sin usuario. NO guarda mensajes, audios ni transcripciones.
-- =====================================================================================

CREATE TABLE telegram_bot
(
    organization_id bigint NOT NULL,
    token_cifrado text,
    bot_id bigint NOT NULL,
    bot_usuario varchar(64) NOT NULL,
    activo boolean NOT NULL,
    ultimo_update_id bigint NOT NULL DEFAULT 0,
    tomado_hasta timestamptz(6),
    ultimo_error varchar(300),
    ultimo_contacto_en timestamptz(6),
    configurado_por bigint NOT NULL,
    creado_en timestamptz(6) NOT NULL,
    actualizado_en timestamptz(6) NOT NULL,
    CONSTRAINT pk_telegram_bot PRIMARY KEY (organization_id),
    CONSTRAINT fk_telegram_bot_org FOREIGN KEY (organization_id) REFERENCES organization (id),
    CONSTRAINT fk_telegram_bot_cuenta FOREIGN KEY (configurado_por) REFERENCES cuenta (id),
    CONSTRAINT ck_telegram_bot_token CHECK (activo = false OR token_cifrado IS NOT NULL)
);
COMMENT ON TABLE telegram_bot IS 'Bot de Telegram del centro. Token cifrado; al desconectar se borra el token y queda activo = false.';

CREATE TABLE telegram_vinculo
(
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    organization_id bigint NOT NULL,
    cuenta_id bigint NOT NULL,
    consultorio_id bigint NOT NULL,
    codigo varchar(12),
    codigo_vence_en timestamptz(6),
    codigo_consultorio_id bigint,
    telegram_usuario_id bigint,
    telegram_nombre varchar(120),
    vinculado_en timestamptz(6),
    creado_en timestamptz(6) NOT NULL,
    actualizado_en timestamptz(6) NOT NULL,
    CONSTRAINT pk_telegram_vinculo PRIMARY KEY (id),
    CONSTRAINT fk_telegram_vinculo_org FOREIGN KEY (organization_id) REFERENCES organization (id),
    CONSTRAINT fk_telegram_vinculo_cuenta FOREIGN KEY (cuenta_id) REFERENCES cuenta (id),
    CONSTRAINT fk_telegram_vinculo_consultorio FOREIGN KEY (consultorio_id) REFERENCES consultorio (id),
    CONSTRAINT fk_telegram_vinculo_codigo_consultorio FOREIGN KEY (codigo_consultorio_id) REFERENCES consultorio (id),
    CONSTRAINT uq_telegram_vinculo_cuenta UNIQUE (organization_id, cuenta_id),
    CONSTRAINT uq_telegram_vinculo_usuario UNIQUE (organization_id, telegram_usuario_id),
    CONSTRAINT uq_telegram_vinculo_codigo UNIQUE (organization_id, codigo)
);
COMMENT ON TABLE telegram_vinculo IS 'Cuenta de AKINE vinculada a un usuario de Telegram, con la sede en la que carga. Sin mensajes ni audios.';
