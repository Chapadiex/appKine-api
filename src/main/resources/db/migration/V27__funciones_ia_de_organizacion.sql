-- =====================================================================================
-- AKINE — Funciones de inteligencia artificial por centro.
--
-- El despliegue decide si cada funcion EXISTE (akine.asistente.enabled, akine.evolucion.*,
-- akine.biblioteca.*). Esta tabla decide si el centro la QUIERE usar: la cambia su ORG_ADMIN
-- desde Organizacion -> Inteligencia artificial. Activa = las dos prendidas.
--
-- Una fila por organizacion, creada en la primera edicion. Sin fila, todo prendido: un centro
-- que nunca toco la pantalla usa lo que el despliegue ofrece.
-- =====================================================================================

CREATE TABLE organization_ia
(
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    organization_id bigint NOT NULL,
    asistente boolean DEFAULT true NOT NULL,
    evolucion boolean DEFAULT true NOT NULL,
    sugerencias boolean DEFAULT true NOT NULL,
    biblioteca boolean DEFAULT true NOT NULL,
    version bigint DEFAULT 0 NOT NULL,
    created_at timestamptz(6) NOT NULL,
    updated_at timestamptz(6) NOT NULL,
    CONSTRAINT pk_organization_ia PRIMARY KEY (id),
    CONSTRAINT uk_organization_ia_org UNIQUE (organization_id),
    CONSTRAINT fk_organization_ia_org FOREIGN KEY (organization_id) REFERENCES organization (id)
);
COMMENT ON TABLE organization_ia IS 'Funciones de IA que el centro decidio usar. Una fila por organizacion, creada en la primera edicion; sin fila, todas prendidas. La funcion queda activa solo si ademas el despliegue la ofrece.';
