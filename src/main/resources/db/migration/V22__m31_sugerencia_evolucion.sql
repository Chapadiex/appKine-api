-- M31 fase 2: sugerencias de revision que el modelo propone al profesional sobre un Caso Clinico.
-- Cada fila es UNA sugerencia mostrada, con su evidencia (citas de la biblioteca) y la respuesta del
-- profesional. Propietario: modulo encounter. Las sugerencias no se borran: baja logica por convencion.
CREATE TABLE sugerencia_evolucion
(
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    organization_id bigint NOT NULL,
    caso_id bigint NOT NULL,
    historia_clinica_id bigint NOT NULL,
    generacion_id uuid NOT NULL,
    solicitada_por_cuenta_id bigint NOT NULL,
    solicitada_en timestamptz(6) NOT NULL,
    hallazgo_codigo varchar(40) COLLATE akine_ci NOT NULL,
    texto varchar(280) COLLATE akine_ci NOT NULL,
    fundamento varchar(600) COLLATE akine_ci NOT NULL,
    citas jsonb NOT NULL,
    sesiones jsonb NOT NULL,
    modelo varchar(80) COLLATE akine_ci NOT NULL,
    respuesta varchar(12) COLLATE akine_ci DEFAULT 'PENDIENTE' NOT NULL,
    respondida_por_cuenta_id bigint,
    respondida_en timestamptz(6),
    motivo_descarte varchar(300) COLLATE akine_ci,
    active boolean DEFAULT true NOT NULL,
    deleted_at timestamptz(6),
    deactivation_reason varchar(280) COLLATE akine_ci,
    deleted_key timestamptz(6) GENERATED ALWAYS AS (COALESCE(deleted_at, '1970-01-01 00:00:00+00'::timestamptz)) STORED,
    version bigint DEFAULT 0 NOT NULL,
    created_at timestamptz(6) NOT NULL,
    updated_at timestamptz(6) NOT NULL,
    CONSTRAINT sugerencia_evolucion_pk PRIMARY KEY (id),
    CONSTRAINT sugerencia_evolucion_ck_hallazgo CHECK (hallazgo_codigo IN ('DOLOR_SIN_MEJORA','DOLOR_EN_AUMENTO','EVOLUCION_DESFAVORABLE','MALA_TOLERANCIA','MEDICION_SIN_CAMBIO','MEDICION_EMPEORA','BAJA_ADHERENCIA','FRECUENCIA_BAJO_PLAN','PLAN_EXCEDIDO_EN_TIEMPO')),
    CONSTRAINT sugerencia_evolucion_ck_respuesta CHECK (respuesta IN ('PENDIENTE','ACEPTADA','DESCARTADA')),
    CONSTRAINT sugerencia_evolucion_ck_motivo CHECK (respuesta <> 'DESCARTADA' OR motivo_descarte IS NOT NULL),
    CONSTRAINT sugerencia_evolucion_fk_caso FOREIGN KEY (caso_id) REFERENCES caso_clinico (id),
    CONSTRAINT sugerencia_evolucion_fk_historia FOREIGN KEY (historia_clinica_id) REFERENCES historia_clinica (id),
    CONSTRAINT sugerencia_evolucion_fk_organization FOREIGN KEY (organization_id) REFERENCES organization (id)
);
CREATE INDEX sugerencia_evolucion_ix_caso ON sugerencia_evolucion (organization_id, caso_id, solicitada_en DESC);
CREATE INDEX sugerencia_evolucion_ix_historia ON sugerencia_evolucion (historia_clinica_id);
CREATE INDEX sugerencia_evolucion_ix_generacion ON sugerencia_evolucion (organization_id, generacion_id);

COMMENT ON TABLE sugerencia_evolucion IS 'Sugerencia de revision generada por el modelo para un Caso Clinico, con sus citas y la respuesta del profesional (M31 fase 2). Propietario: modulo encounter. Es contenido clinico: se lee con hc:read y se audita';
COMMENT ON COLUMN sugerencia_evolucion.generacion_id IS 'Agrupa las sugerencias de un mismo pedido';
COMMENT ON COLUMN sugerencia_evolucion.citas IS 'Lista de {libroId,titulo,paginaDesde,paginaHasta,puntaje,sha256}. El sha256 es del texto del pasaje: prueba despues si el pasaje citado cambio';
COMMENT ON COLUMN sugerencia_evolucion.sesiones IS 'Ids de las sesiones del hallazgo';
COMMENT ON COLUMN sugerencia_evolucion.modelo IS 'Nombre exacto del modelo que la genero';
COMMENT ON COLUMN sugerencia_evolucion.respuesta IS 'PENDIENTE, ACEPTADA o DESCARTADA. Solo se sale de PENDIENTE una vez';
COMMENT ON COLUMN sugerencia_evolucion.motivo_descarte IS 'Obligatorio con DESCARTADA';
COMMENT ON COLUMN sugerencia_evolucion.solicitada_por_cuenta_id IS 'accountId de quien pidio las sugerencias. Sin FK a cuenta: es de identity';
COMMENT ON COLUMN sugerencia_evolucion.respondida_por_cuenta_id IS 'accountId de quien respondio. Sin FK a cuenta: es de identity';
COMMENT ON COLUMN sugerencia_evolucion.deleted_key IS 'Mismo centinela que en V7: no hay unique que lo use hoy, queda por convencion';
COMMENT ON COLUMN sugerencia_evolucion.version IS 'Bloqueo optimista de la respuesta';
