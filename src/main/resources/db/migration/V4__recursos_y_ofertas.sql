    CONSTRAINT ck_espacio_tipo CHECK (tipo in ('BOX','GIMNASIO','GABINETE','SALA_GRUPAL','PILETA','OTRO')),
    CONSTRAINT ck_espacio_vigencia_coherente CHECK ((valid_until is null) or (valid_until > valid_from))
