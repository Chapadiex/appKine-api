-- Baseline PostgreSQL consolidado (11/11/2026). Reemplaza las 145 migraciones de MySQL, que quedan
-- como archivo historico en ops/migracion-mysql/mysql-historico. Generado por
-- ops/migracion-mysql/generar-baseline.mjs desde el esquema final de MySQL y revisado a mano.
--
-- Convenciones que vienen de MySQL y se conservan:
--   * Textos con COLLATE akine_ci: comparacion sin mayusculas ni tildes, como utf8mb4_0900_ai_ci.
--   * Instantes en timestamptz (UTC); fechas en date; horas de agenda en time.
--   * Las claves *_key generadas sostienen los UNIQUE de la baja logica (centinela 1970-01-01).
--   * Las claves foraneas se crean todas juntas en V11, despues de todas las tablas.
-- =====================================================================================

CREATE TABLE agenda_profesional
(
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    organization_id bigint NOT NULL,
    account_id bigint NOT NULL,
    created_at timestamptz(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_agenda_profesional PRIMARY KEY (id),
    CONSTRAINT uk_agenda_profesional UNIQUE (organization_id, account_id)
);
COMMENT ON TABLE agenda_profesional IS 'Fila por persona y organizacion que sirve unicamente para serializar con FOR UPDATE las escrituras de agenda de esa persona en cualquier sede. No guarda estado.';

CREATE TABLE catalogo_solicitud
(
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    organization_id bigint NOT NULL,
    consultorio_id bigint,
    tipo varchar(24) COLLATE akine_ci NOT NULL,
    nombre_propuesto varchar(160) COLLATE akine_ci NOT NULL,
    codigo_propuesto varchar(48) COLLATE akine_ci,
    justificacion varchar(500) COLLATE akine_ci NOT NULL,
    estado varchar(16) COLLATE akine_ci DEFAULT 'PENDIENTE' NOT NULL,
    solicitada_por_account_id bigint NOT NULL,
    resuelta_por_account_id bigint,
    resuelta_at timestamptz(6),
    resolucion_nota varchar(500) COLLATE akine_ci,
    concepto_id bigint,
    nombre_pendiente varchar(160) COLLATE akine_ci GENERATED ALWAYS AS (CASE WHEN estado = 'PENDIENTE' THEN nombre_propuesto END) STORED,
    version bigint DEFAULT 0 NOT NULL,
    created_at timestamptz(6) NOT NULL,
    updated_at timestamptz(6) NOT NULL,
    CONSTRAINT pk_catalogo_solicitud PRIMARY KEY (id),
    CONSTRAINT uk_catalogo_solicitud_pendiente UNIQUE (organization_id, tipo, nombre_pendiente),
    CONSTRAINT ck_catalogo_solicitud_estado CHECK (estado in ('PENDIENTE','APROBADA','RECHAZADA')),
    CONSTRAINT ck_catalogo_solicitud_resolucion_coherente CHECK (((estado = 'PENDIENTE') and (resuelta_por_account_id is null) and (resuelta_at is null) and (resolucion_nota is null)) or ((estado <> 'PENDIENTE') and (resuelta_por_account_id is not null) and (resuelta_at is not null) and (resolucion_nota is not null))),
    CONSTRAINT ck_catalogo_solicitud_tipo CHECK (tipo in ('ESPECIALIDAD','PRACTICA','NOMENCLADOR'))
);
CREATE INDEX fk_catalogo_solicitud_consultorio ON catalogo_solicitud (consultorio_id);
CREATE INDEX ix_catalogo_solicitud_bandeja ON catalogo_solicitud (estado, created_at);
CREATE INDEX ix_catalogo_solicitud_tenant ON catalogo_solicitud (organization_id, estado, created_at);
COMMENT ON TABLE catalogo_solicitud IS 'Pedido de un tenant para que la plataforma incorpore un concepto GLOBAL al catalogo (M06, RF-M06-005). Propietario: modulo resource';
COMMENT ON COLUMN catalogo_solicitud.organization_id IS 'Tenant que solicita. NOT NULL sin excepcion: no existen solicitudes sin tenant, asi que ADR-0021 no la alcanza';
COMMENT ON COLUMN catalogo_solicitud.consultorio_id IS 'Sede desde la que se pidio, si la habia en el contexto. Es trazabilidad, no alcance: la solicitud es de la organizacion';
COMMENT ON COLUMN catalogo_solicitud.tipo IS 'Que concepto global se pide';
COMMENT ON COLUMN catalogo_solicitud.codigo_propuesto IS 'Codigo sugerido. Opcional: el centro propone, la plataforma dispone';
COMMENT ON COLUMN catalogo_solicitud.justificacion IS 'Por que hace falta. Obligatoria: sin ella la plataforma no puede decidir y la solicitud es ruido';
COMMENT ON COLUMN catalogo_solicitud.resolucion_nota IS 'Motivo de la aprobacion o del rechazo. Obligatorio al resolver';
COMMENT ON COLUMN catalogo_solicitud.concepto_id IS 'Id del concepto GLOBAL creado al aprobar, si se creo. Sin FK: apunta a una de tres tablas segun tipo, y una FK solo puede apuntar a una';
COMMENT ON COLUMN catalogo_solicitud.nombre_pendiente IS 'Discriminador del unique de duplicados: vale el nombre mientras la solicitud esta PENDIENTE y NULL en cuanto se resuelve. Es la forma de V12 —NULL a proposito— y aca es la correcta: pedir de nuevo algo ya rechazado es legitimo, pedir dos veces lo mismo mientras esta pendiente no';

