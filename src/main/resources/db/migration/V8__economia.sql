CREATE TABLE egreso
(
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    organization_id bigint NOT NULL,
    consultorio_id bigint NOT NULL,
    oferta_id bigint,
    categoria varchar(32) COLLATE akine_ci NOT NULL,
    tipo_beneficiario varchar(16) COLLATE akine_ci NOT NULL,
    beneficiario_membership_id bigint,
    beneficiario_clave varchar(80) COLLATE akine_ci NOT NULL,
    beneficiario_nombre varchar(160) COLLATE akine_ci NOT NULL,
    beneficiario_documento varchar(32) COLLATE akine_ci,
    periodo_desde date,
    periodo_hasta date,
    concepto varchar(280) COLLATE akine_ci NOT NULL,
    importe_total numeric(12,2) NOT NULL,
    saldo_pendiente numeric(12,2) NOT NULL,
    moneda varchar(3) COLLATE akine_ci NOT NULL,
    estado varchar(16) COLLATE akine_ci NOT NULL,
    comprobante_tipo varchar(24) COLLATE akine_ci,
    comprobante_numero varchar(40) COLLATE akine_ci,
    comprobante_fecha date,
    registrado_en timestamptz(6) NOT NULL,
    registrado_por_cuenta_id bigint NOT NULL,
    confirmado_en timestamptz(6),
    confirmado_por_cuenta_id bigint,
    anulado_en timestamptz(6),
    anulado_por_cuenta_id bigint,
    motivo_anulacion varchar(280) COLLATE akine_ci,
    anulado_key timestamptz(6) GENERATED ALWAYS AS (COALESCE(anulado_en, '1970-01-01 00:00:00+00'::timestamptz)) STORED,
    idempotency_key varchar(80) COLLATE akine_ci,
    request_hash varchar(64) COLLATE akine_ci,
    version bigint DEFAULT 0 NOT NULL,
    created_at timestamptz(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at timestamptz(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_egreso PRIMARY KEY (id),
    CONSTRAINT uk_egreso_comprobante UNIQUE (organization_id, beneficiario_clave, comprobante_tipo, comprobante_numero, anulado_key),
    CONSTRAINT uk_egreso_idempotencia UNIQUE (organization_id, idempotency_key),
    CONSTRAINT ck_egreso_anulacion_completa CHECK (((estado = 'ANULADO') = (anulado_en is not null)) and ((anulado_en is null) or ((anulado_por_cuenta_id is not null) and (motivo_anulacion is not null)))),
    CONSTRAINT ck_egreso_beneficiario_coherente CHECK ((tipo_beneficiario = 'COLABORADOR') = (beneficiario_membership_id is not null)),
    CONSTRAINT ck_egreso_borrador_sin_pagos CHECK ((estado <> 'BORRADOR') or (saldo_pendiente = importe_total)),
    CONSTRAINT ck_egreso_categoria CHECK (categoria in ('HONORARIOS_PROFESIONALES','ALQUILER','SERVICIOS','INSUMOS','IMPUESTOS','MANTENIMIENTO','SUELDOS','OTRO')),
    CONSTRAINT ck_egreso_confirmacion_completa CHECK (((confirmado_en is null) = (confirmado_por_cuenta_id is null)) and ((estado = 'BORRADOR') or (estado = 'ANULADO') or (confirmado_en is not null))),
    CONSTRAINT ck_egreso_estado CHECK (estado in ('BORRADOR','CONFIRMADO','PAGADO','ANULADO')),
    CONSTRAINT ck_egreso_idempotencia_completa CHECK (((idempotency_key is null) and (request_hash is null)) or ((idempotency_key is not null) and (request_hash is not null))),
    CONSTRAINT ck_egreso_importe_positivo CHECK (importe_total > 0),
    CONSTRAINT ck_egreso_periodo_coherente CHECK (((periodo_desde is null) = (periodo_hasta is null)) and ((periodo_desde is null) or (periodo_desde <= periodo_hasta))),
    CONSTRAINT ck_egreso_saldo_acotado CHECK (saldo_pendiente <= importe_total),
    CONSTRAINT ck_egreso_saldo_no_negativo CHECK (saldo_pendiente >= 0),
    CONSTRAINT ck_egreso_tipo_beneficiario CHECK (tipo_beneficiario in ('COLABORADOR','EXTERNO'))
);
CREATE INDEX fk_egreso_consultorio ON egreso (consultorio_id);
CREATE INDEX fk_egreso_membership ON egreso (beneficiario_membership_id);
CREATE INDEX fk_egreso_oferta ON egreso (oferta_id);
CREATE INDEX ix_egreso_beneficiario ON egreso (organization_id, beneficiario_clave, estado);
CREATE INDEX ix_egreso_periodo ON egreso (organization_id, consultorio_id, periodo_desde, periodo_hasta);
CREATE INDEX ix_egreso_sede_estado ON egreso (organization_id, consultorio_id, estado, registrado_en);
COMMENT ON TABLE egreso IS 'Lo que el centro DEBE a un beneficiario. No es el pago (pago_egreso) ni el hecho monetario (movimiento_caja).';
COMMENT ON COLUMN egreso.consultorio_id IS 'Un egreso se paga desde la caja de UNA sede, igual que la jornada de V54.';
COMMENT ON COLUMN egreso.oferta_id IS 'Oferta de la misma sede a la que se imputa el costo (DP-39). NULL = sin imputar.';
