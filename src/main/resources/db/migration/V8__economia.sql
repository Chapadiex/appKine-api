COMMENT ON COLUMN egreso.periodo_desde IS 'Periodo liquidado. Los dos NULL o los dos presentes. NO hay unique: dos liquidaciones del mismo mes son legitimas.';
COMMENT ON COLUMN egreso.importe_total IS 'Declarado por una persona. Esta etapa NO calcula liquidaciones.';
COMMENT ON COLUMN egreso.saldo_pendiente IS 'Punto 3 de la cabecera. Arranca igual al total.';
