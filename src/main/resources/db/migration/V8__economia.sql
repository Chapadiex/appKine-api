-- =====================================================================================
-- AKINE — billing
--
-- Baseline PostgreSQL consolidado (11/11/2026). Reemplaza las 145 migraciones de MySQL, que quedan
-- como archivo historico en ops/migracion-mysql/mysql-historico. Generado por
-- ops/migracion-mysql/generar-baseline.mjs desde el esquema final de MySQL y revisado a mano.
--
-- Convenciones que vienen de MySQL y se conservan:
--   * Textos con COLLATE akine_ci: comparacion sin mayusculas ni tildes, como utf8mb4_0900_ai_ci.
--   * Instantes en timestamptz (UTC); fechas en date; horas de agenda en time.
--   * Las claves *_key generadas sostienen los UNIQUE de la baja logica (centinela 1970-01-01).
--   * Las claves foraneas se crean todas juntas en V11, despues de todas las tablas.
-- =====================================================================================

CREATE TABLE cobro
(
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    organization_id bigint NOT NULL,
    consultorio_id bigint NOT NULL,
    persona_id bigint NOT NULL,
    turno_id bigint,
    total numeric(12,2) NOT NULL,
    moneda varchar(3) COLLATE akine_ci NOT NULL,
    saldo_a_favor numeric(12,2) DEFAULT 0.00 NOT NULL,
    comprobante_numero integer NOT NULL,
    cobrado_en timestamptz(6) NOT NULL,
    cobrado_por_cuenta_id bigint NOT NULL,
    idempotency_key varchar(80) COLLATE akine_ci,
    request_hash varchar(64) COLLATE akine_ci,
    created_at timestamptz(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at timestamptz(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    deleted_at timestamptz(6),
    anulado_por_cuenta_id bigint,
    motivo_anulacion varchar(280) COLLATE akine_ci,
    deleted_key timestamptz(6) GENERATED ALWAYS AS (COALESCE(deleted_at, '1970-01-01 00:00:00+00'::timestamptz)) STORED,
    version bigint DEFAULT 0 NOT NULL,
    turno_prepago_vigente bigint GENERATED ALWAYS AS (CASE WHEN deleted_at IS NULL THEN turno_id END) STORED,
    CONSTRAINT pk_cobro PRIMARY KEY (id),
    CONSTRAINT uk_cobro_comprobante UNIQUE (organization_id, consultorio_id, comprobante_numero),
    CONSTRAINT uk_cobro_idempotencia UNIQUE (organization_id, idempotency_key),
    CONSTRAINT uk_cobro_prepago_turno_vigente UNIQUE (organization_id, turno_prepago_vigente),
    CONSTRAINT ck_cobro_anulacion_completa CHECK (((deleted_at is null) and (anulado_por_cuenta_id is null) and (motivo_anulacion is null)) or ((deleted_at is not null) and (anulado_por_cuenta_id is not null) and (motivo_anulacion is not null))),
    CONSTRAINT ck_cobro_anulado_sin_saldo CHECK ((deleted_at is null) or (saldo_a_favor = 0)),
    CONSTRAINT ck_cobro_idempotencia_completa CHECK (((idempotency_key is null) and (request_hash is null)) or ((idempotency_key is not null) and (request_hash is not null))),
    CONSTRAINT ck_cobro_saldo_a_favor CHECK ((saldo_a_favor >= 0) and (saldo_a_favor <= total)),
    CONSTRAINT ck_cobro_total_positivo CHECK (total > 0)
);
CREATE INDEX fk_cobro_consultorio ON cobro (consultorio_id);
CREATE INDEX fk_cobro_persona ON cobro (persona_id);
CREATE INDEX ix_cobro_persona ON cobro (organization_id, persona_id, cobrado_en);
CREATE INDEX ix_cobro_sede_fecha ON cobro (organization_id, consultorio_id, cobrado_en);
CREATE INDEX ix_cobro_turno ON cobro (organization_id, turno_id);
COMMENT ON TABLE cobro IS 'Dinero recibido. No es la deuda (M18) ni la caja (M20).';
COMMENT ON COLUMN cobro.consultorio_id IS 'Donde se cobro. El comprobante es correlativo por sede.';
COMMENT ON COLUMN cobro.persona_id IS 'Quien pago.';
COMMENT ON COLUMN cobro.turno_id IS 'E-6: turno en cuya recepcion se tomo este anticipo (prepago). NULL en cualquier otro cobro';
COMMENT ON COLUMN cobro.saldo_a_favor IS 'Lo recibido que todavia no se imputo ni se reintegro. Anticipo cuando es > 0.';
COMMENT ON COLUMN cobro.comprobante_numero IS 'Correlativo por sede. Ver el punto 4.';
COMMENT ON COLUMN cobro.request_hash IS 'SHA-256 del pedido, igual que en turno (V30).';
COMMENT ON COLUMN cobro.anulado_por_cuenta_id IS 'Quien anulo. La fecha es deleted_at (V37 la reservo para esto).';
COMMENT ON COLUMN cobro.turno_prepago_vigente IS 'E-6: turno_id mientras el prepago esta vigente; NULL si se anulo o no es prepago';

