CREATE TABLE jornada_caja
(
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    organization_id bigint NOT NULL,
    consultorio_id bigint NOT NULL,
    fecha_negocio date NOT NULL,
    moneda varchar(3) COLLATE akine_ci NOT NULL,
    estado varchar(16) COLLATE akine_ci NOT NULL,
    saldo_inicial numeric(12,2) NOT NULL,
    saldo_arqueo numeric(12,2) NOT NULL,
    abierta_en timestamptz(6) NOT NULL,
    abierta_por_cuenta_id bigint NOT NULL,
    cerrada_en timestamptz(6),
    cerrada_por_cuenta_id bigint,
    saldo_teorico_cierre numeric(12,2),
    saldo_declarado numeric(12,2),
    diferencia numeric(12,2),
    motivo_diferencia varchar(280) COLLATE akine_ci,
    abierta_marca smallint GENERATED ALWAYS AS (CASE WHEN estado = 'ABIERTA' THEN 1 END) STORED,
    created_at timestamptz(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at timestamptz(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_jornada_caja PRIMARY KEY (id),
    CONSTRAINT uk_jornada_caja_abierta UNIQUE (organization_id, consultorio_id, abierta_marca),
    CONSTRAINT ck_jornada_caja_cierre_completo CHECK (((estado = 'ABIERTA') and (cerrada_en is null) and (cerrada_por_cuenta_id is null) and (saldo_teorico_cierre is null) and (saldo_declarado is null) and (diferencia is null) and (motivo_diferencia is null)) or ((estado = 'CERRADA') and (cerrada_en is not null) and (cerrada_por_cuenta_id is not null) and (saldo_teorico_cierre is not null) and (saldo_declarado is not null) and (diferencia is not null))),
    CONSTRAINT ck_jornada_caja_estado CHECK (estado in ('ABIERTA','CERRADA')),
    CONSTRAINT ck_jornada_caja_motivo_de_diferencia CHECK ((diferencia is null) or ((diferencia = 0) and (motivo_diferencia is null)) or ((diferencia <> 0) and (motivo_diferencia is not null))),
    CONSTRAINT ck_jornada_caja_saldo_declarado CHECK ((saldo_declarado is null) or (saldo_declarado >= 0)),
    CONSTRAINT ck_jornada_caja_saldo_inicial CHECK (saldo_inicial >= 0),
    CONSTRAINT ck_jornada_caja_saldo_no_negativo CHECK (saldo_arqueo >= 0)
);
CREATE INDEX fk_jornada_caja_consultorio ON jornada_caja (consultorio_id);
CREATE INDEX ix_jornada_caja_sede_fecha ON jornada_caja (organization_id, consultorio_id, fecha_negocio, estado);
COMMENT ON TABLE jornada_caja IS 'Turno de caja de una sede. No es el cobro (M19) ni la deuda (M18).';
COMMENT ON COLUMN jornada_caja.consultorio_id IS 'UNA CAJA PERTENECE A UNA SEDE. Punto 1 de la cabecera.';
