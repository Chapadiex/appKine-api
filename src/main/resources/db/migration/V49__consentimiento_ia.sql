-- =====================================================================================
-- AKINE — Consentimiento del centro para usar inteligencia artificial (Ley 25.326).
--
-- El ORG_ADMIN acepta, en nombre del centro, la version vigente del texto
-- (akine.ia.consentimiento.version). Sin una fila de esa version, ninguna funcion de IA
-- corre, sea con el modelo local o con un proveedor externo.
--
-- Solo inserciones: una fila por centro y version, que nunca se pisa ni se borra. Es la
-- prueba de quien acepto, cuando y sobre que texto. El nombre se copia al aceptar para que
-- la prueba no dependa de que la cuenta siga existiendo.
-- =====================================================================================

CREATE TABLE organization_ia_consentimiento
(
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    organization_id bigint NOT NULL,
    version varchar(32) NOT NULL,
    account_id bigint NOT NULL,
    nombre varchar(200),
    aceptado_at timestamptz(6) NOT NULL,
    CONSTRAINT pk_organization_ia_consentimiento PRIMARY KEY (id),
    CONSTRAINT uk_organization_ia_consentimiento UNIQUE (organization_id, version),
    CONSTRAINT fk_organization_ia_consentimiento_org FOREIGN KEY (organization_id) REFERENCES organization (id)
);
COMMENT ON TABLE organization_ia_consentimiento IS 'Aceptaciones del consentimiento de IA, una por centro y version del texto. Solo inserciones: nunca se actualiza ni se borra.';
