-- AKINE — clinical, encounter
--
-- Baseline PostgreSQL consolidado (11/11/2026). Reemplaza las 145 migraciones de MySQL, que quedan
-- como archivo historico en ops/migracion-mysql/mysql-historico. Generado por
-- ops/migracion-mysql/generar-baseline.mjs desde el esquema final de MySQL y revisado a mano.
--
-- Convenciones que vienen de MySQL y se conservan:
--   * Textos con COLLATE akine_ci: comparacion sin mayusculas ni tildes, como utf8mb4_0900_ai_ci.
--   * Instantes en timestamptz (UTC); fechas en date; horas de agenda en time.
--   * Las claves *_key generadas sostienen los UNIQUE de la baja logica (centinela 1970-01-01).
--   * Las claves foraneas se crean todas juntas en V11, despues de todas las tablas.
-- =====================================================================================

CREATE TABLE adjunto_clinico
(
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    organization_id bigint NOT NULL,
    historia_clinica_id bigint NOT NULL,
    entrada_clinica_id bigint,
    consultorio_id bigint,
    categoria varchar(32) COLLATE akine_ci NOT NULL,
    titulo varchar(160) COLLATE akine_ci,
    nombre_archivo varchar(255) COLLATE akine_ci NOT NULL,
    content_type varchar(120) COLLATE akine_ci NOT NULL,
    tamano_bytes bigint NOT NULL,
    checksum_sha256 varchar(64) COLLATE akine_ci NOT NULL,
    storage_key varchar(64) COLLATE akine_ci NOT NULL,
    estado varchar(24) COLLATE akine_ci DEFAULT 'DISPONIBLE' NOT NULL,
    subido_por bigint NOT NULL,
    subido_en timestamptz(6) NOT NULL,
    active boolean DEFAULT true NOT NULL,
    deleted_at timestamptz(6),
    deactivation_reason varchar(280) COLLATE akine_ci,
    deleted_key timestamptz(6) GENERATED ALWAYS AS (COALESCE(deleted_at, '1970-01-01 00:00:00+00'::timestamptz)) STORED,
    version bigint DEFAULT 0 NOT NULL,
    created_at timestamptz(6) NOT NULL,
    updated_at timestamptz(6) NOT NULL,
    CONSTRAINT pk_adjunto_clinico PRIMARY KEY (id),
    CONSTRAINT uk_adjunto_clinico_contenido_vigente UNIQUE (organization_id, historia_clinica_id, checksum_sha256, deleted_key),
    CONSTRAINT uk_adjunto_clinico_storage_key UNIQUE (storage_key),
    CONSTRAINT ck_adjunto_clinico_baja_coherente CHECK (((active = true) and (deleted_at is null) and (deactivation_reason is null)) or ((active = false) and (deleted_at is not null) and (deactivation_reason is not null))),
    CONSTRAINT ck_adjunto_clinico_categoria CHECK (categoria in ('ESTUDIO','INFORME','IMAGEN','CONSENTIMIENTO_CLINICO','EVOLUCION_ESCANEADA','OTRO')),
    CONSTRAINT ck_adjunto_clinico_estado CHECK (estado in ('DISPONIBLE','NO_DISPONIBLE')),
    CONSTRAINT ck_adjunto_clinico_tamano CHECK (tamano_bytes > 0)
);
CREATE INDEX fk_adjunto_clinico_entrada ON adjunto_clinico (entrada_clinica_id);
CREATE INDEX fk_adjunto_clinico_historia ON adjunto_clinico (historia_clinica_id);
CREATE INDEX ix_adjunto_clinico_entrada ON adjunto_clinico (organization_id, entrada_clinica_id, active);
CREATE INDEX ix_adjunto_clinico_historia ON adjunto_clinico (organization_id, historia_clinica_id, active, categoria);
