CREATE TABLE caso_evento
(
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    organization_id bigint NOT NULL,
    caso_id bigint NOT NULL,
    tipo varchar(24) COLLATE akine_ci NOT NULL,
    estado_anterior varchar(16) COLLATE akine_ci,
    estado_nuevo varchar(16) COLLATE akine_ci NOT NULL,
    motivo varchar(500) COLLATE akine_ci,
    detalle varchar(500) COLLATE akine_ci,
    ocurrio_en timestamptz(6) NOT NULL,
    actor_cuenta_id bigint NOT NULL,
    created_at timestamptz(6) NOT NULL,
    CONSTRAINT pk_caso_evento PRIMARY KEY (id),
    CONSTRAINT ck_caso_evento_apertura CHECK (((tipo = 'APERTURA') and (estado_anterior is null)) or ((tipo <> 'APERTURA') and (estado_anterior is not null))),
    CONSTRAINT ck_caso_evento_estados CHECK ((estado_nuevo in ('ACTIVO','CERRADO')) and ((estado_anterior is null) or (estado_anterior in ('ACTIVO','CERRADO')))),
    CONSTRAINT ck_caso_evento_motivo CHECK (((tipo in ('CIERRE','REAPERTURA')) and (motivo is not null)) or (tipo not in ('CIERRE','REAPERTURA'))),
    CONSTRAINT ck_caso_evento_tipo CHECK (tipo in ('APERTURA','EDICION','CIERRE','REAPERTURA','CAMBIO_DE_EQUIPO'))
);
CREATE INDEX fk_caso_evento_caso ON caso_evento (caso_id);
CREATE INDEX ix_caso_evento_caso ON caso_evento (organization_id, caso_id, ocurrio_en);
COMMENT ON TABLE caso_evento IS 'Historial inmutable de estados de un Caso Clinico (RF-M10-006). APPEND-ONLY: sin updated_at, sin version, sin baja. Mismo diseño que turno_evento (V38). Propietario: modulo clinical';
