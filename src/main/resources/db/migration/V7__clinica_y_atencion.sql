COMMENT ON COLUMN caso_clinico.historia_clinica_id IS 'Historia de la que cuelga el caso. La HC existe sin casos y el caso no existe sin HC (regla maestra 1)';
COMMENT ON COLUMN caso_clinico.numero_caso IS 'Correlativo del caso DENTRO de la historia. Sale de caso_numerador con UPDATE ultimo_numero + 1, nunca de un MAX. Ver el punto 1';
COMMENT ON COLUMN caso_clinico.oferta_id IS 'Oferta que motiva el caso. RN-M10-006: la necesidad de Caso la determina la Oferta efectiva';
COMMENT ON COLUMN caso_clinico.oferta_consultorio_id IS 'Sede de la OFERTA, no del caso. La oferta es por sede (V24) y sin esta columna oferta_id no se puede volver a resolver; el caso sigue siendo de la ORGANIZACION';
