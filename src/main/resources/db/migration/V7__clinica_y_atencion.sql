CREATE TABLE caso_clinico
(
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    organization_id bigint NOT NULL,
    historia_clinica_id bigint NOT NULL,
    numero_caso integer NOT NULL,
    oferta_id bigint NOT NULL,
    oferta_consultorio_id bigint NOT NULL,
    diagnostico_presuntivo varchar(500) COLLATE akine_ci NOT NULL,
    objetivo_terapeutico varchar(1000) COLLATE akine_ci,
    estado varchar(16) COLLATE akine_ci DEFAULT 'ACTIVO' NOT NULL,
    abierto_en timestamptz(6) NOT NULL,
    abierto_por bigint NOT NULL,
    cerrado_en timestamptz(6),
    cerrado_por bigint,
    motivo_cierre varchar(500) COLLATE akine_ci,
    version bigint DEFAULT 0 NOT NULL,
    created_at timestamptz(6) NOT NULL,
    updated_at timestamptz(6) NOT NULL,
    CONSTRAINT pk_caso_clinico PRIMARY KEY (id),
    CONSTRAINT uk_caso_numero UNIQUE (organization_id, historia_clinica_id, numero_caso),
    CONSTRAINT ck_caso_clinico_cierre_coherente CHECK (((estado = 'ACTIVO') and (cerrado_en is null) and (cerrado_por is null) and (motivo_cierre is null)) or ((estado = 'CERRADO') and (cerrado_en is not null) and (cerrado_por is not null) and (motivo_cierre is not null))),
    CONSTRAINT ck_caso_clinico_estado CHECK (estado in ('ACTIVO','CERRADO')),
    CONSTRAINT ck_caso_clinico_numero_positivo CHECK (numero_caso > 0)
);
CREATE INDEX fk_caso_clinico_historia ON caso_clinico (historia_clinica_id);
CREATE INDEX fk_caso_clinico_oferta ON caso_clinico (oferta_id);
CREATE INDEX ix_caso_clinico_historia ON caso_clinico (organization_id, historia_clinica_id, estado, abierto_en);
CREATE INDEX ix_caso_clinico_oferta ON caso_clinico (organization_id, historia_clinica_id, oferta_id, estado);
CREATE INDEX ix_caso_clinico_sede_apertura ON caso_clinico (organization_id, oferta_consultorio_id, abierto_en);
COMMENT ON TABLE caso_clinico IS 'Problema clinico concreto de un paciente dentro de su Historia Clinica (M10, RF-M10-001). Varios activos a la vez son legitimos (RN-M10-002). Propietario: modulo clinical';
