-- Pedido de cambio de plan (25/11/2026, docs/diseno/AKINE-pedido-de-cambio-de-plan.md).
-- El centro pide subir o bajar de plan desde Suscripcion; la plataforma lo aprueba (se aplica la
-- contratacion pedida) o lo rechaza con motivo. Nunca se borra.

CREATE TABLE pedido_de_cambio_de_plan
(
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    organization_id bigint NOT NULL,
    plan_code varchar(40) NOT NULL,
    kinesiologia boolean NOT NULL,
    actividades boolean NOT NULL,
    ia boolean NOT NULL,
    plan_code_anterior varchar(40) NOT NULL,
    kinesiologia_anterior boolean NOT NULL,
    actividades_anterior boolean NOT NULL,
    ia_anterior boolean NOT NULL,
    comentario varchar(500) COLLATE akine_ci,
    estado varchar(16) NOT NULL,
    motivo_rechazo varchar(500) COLLATE akine_ci,
    pedido_por bigint NOT NULL,
    resuelto_por bigint,
    resuelto_en timestamptz(6),
    version bigint DEFAULT 0 NOT NULL,
    created_at timestamptz(6) NOT NULL,
    updated_at timestamptz(6) NOT NULL,
    CONSTRAINT pk_pedido_de_cambio_de_plan PRIMARY KEY (id),
    CONSTRAINT fk_pedido_de_cambio_de_plan_org FOREIGN KEY (organization_id) REFERENCES organization (id),
    CONSTRAINT ck_pedido_de_cambio_de_plan_estado
        CHECK (estado IN ('PENDIENTE', 'APROBADO', 'RECHAZADO', 'CANCELADO')),
    CONSTRAINT ck_pedido_de_cambio_de_plan_servicio CHECK (kinesiologia OR actividades),
    CONSTRAINT ck_pedido_de_cambio_de_plan_resolucion
        CHECK ((estado = 'PENDIENTE') = (resuelto_en IS NULL)),
    CONSTRAINT ck_pedido_de_cambio_de_plan_motivo
        CHECK (estado <> 'RECHAZADO' OR motivo_rechazo IS NOT NULL)
);

-- Un solo pedido pendiente por centro: el segundo simultaneo choca aca y responde 409.
CREATE UNIQUE INDEX ux_pedido_de_cambio_de_plan_pendiente
    ON pedido_de_cambio_de_plan (organization_id) WHERE estado = 'PENDIENTE';
CREATE INDEX ix_pedido_de_cambio_de_plan_org ON pedido_de_cambio_de_plan (organization_id, created_at);
CREATE INDEX ix_pedido_de_cambio_de_plan_estado ON pedido_de_cambio_de_plan (estado, created_at);

COMMENT ON TABLE pedido_de_cambio_de_plan IS 'Pedidos de cambio de plan que un centro hace desde Suscripcion. Guarda lo pedido y la contratacion de ese momento. La plataforma lo aprueba (aplica la contratacion) o lo rechaza con motivo; el centro puede cancelarlo mientras espera. Nunca se borra. Propietario: modulo organization';
