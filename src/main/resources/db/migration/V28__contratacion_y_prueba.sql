-- =====================================================================================
-- AKINE — Contratacion de un centro y prueba gratis de 30 dias (18/11/2026).
--
-- Diseño: docs/diseno/AKINE-landing-y-ofertas.md. Un centro contrata tres cosas que se
-- combinan: un PLAN (cuantas sedes), uno o los dos SERVICIOS (kinesiologia, actividades) y
-- ADICIONALES (hoy solo la IA). Los centros nuevos los da de alta la plataforma, a veces en
-- PRUEBA por 30 dias. La prueba vencida no se materializa: se calcula al leer comparando
-- prueba_hasta con el reloj, y el centro queda en solo lectura igual que una suspension.
--
-- Nada se le quita a quien ya existe: mientras subscription.contratacion_definida sea false, el
-- centro tiene los dos servicios y la IA, como siempre. La marca la prende la plataforma al dar
-- de alta un centro o al cambiar su contratacion, y desde ahi mandan las filas.
-- =====================================================================================

-- Planes que se ofrecen hoy. BASICO y PROFESIONAL siguen existiendo (los usan las
-- suscripciones y los tests de siempre) pero dejan de ofrecerse en el alta de la plataforma.
ALTER TABLE plan ADD COLUMN ofrecido boolean DEFAULT true NOT NULL;
COMMENT ON COLUMN plan.ofrecido IS 'Si la plataforma lo ofrece al dar de alta o cambiar la contratacion de un centro. Los planes anteriores al 18/11/2026 quedan en false y siguen vigentes para quien los tiene';
UPDATE plan SET ofrecido = false, updated_at = CURRENT_TIMESTAMP WHERE code IN ('BASICO', 'PROFESIONAL');

INSERT INTO plan (code, name, active, ofrecido, version, created_at, updated_at) VALUES
    ('BASE', 'Base', true, true, 0, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP),
    ('CRECIMIENTO', 'Crecimiento', true, true, 0, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP),
    ('RED', 'Red', true, true, 0, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP);

-- NULL = sin tope. Base conserva el tope de miembros de BASICO; Red no tiene tope de sedes
-- ("mas de 3, a convenir").
INSERT INTO plan_limit (plan_id, limit_code, limit_value, active, created_at, updated_at)
SELECT p.id, l.codigo, l.valor, true, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
  FROM plan p
  JOIN (VALUES
      ('BASE', 'MAX_CONSULTORIOS', 1),
      ('BASE', 'MAX_MIEMBROS_ACTIVOS', 5),
      ('CRECIMIENTO', 'MAX_CONSULTORIOS', 3),
      ('CRECIMIENTO', 'MAX_MIEMBROS_ACTIVOS', NULL),
      ('RED', 'MAX_CONSULTORIOS', NULL),
      ('RED', 'MAX_MIEMBROS_ACTIVOS', NULL)
  ) AS l (plan_code, codigo, valor) ON l.plan_code = p.code;

INSERT INTO plan_feature (plan_id, feature_code, active, created_at, updated_at)
SELECT p.id, f.codigo, true, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
  FROM plan p
  JOIN (VALUES
      ('CRECIMIENTO', 'REPORTES_AVANZADOS'),
      ('CRECIMIENTO', 'NOTIFICACIONES_PACIENTE'),
      ('RED', 'REPORTES_AVANZADOS'),
      ('RED', 'NOTIFICACIONES_PACIENTE')
  ) AS f (plan_code, codigo) ON f.plan_code = p.code;

-- Prueba gratis.
ALTER TABLE subscription ADD COLUMN prueba_hasta timestamptz(6);
ALTER TABLE subscription ADD COLUMN contratacion_definida boolean DEFAULT false NOT NULL;
COMMENT ON COLUMN subscription.contratacion_definida IS 'false: el centro tiene todo (los dos servicios y la IA), como antes del 18/11/2026. true: valen solo las filas de subscription_servicio y subscription_adicional';
ALTER TABLE subscription
    ADD CONSTRAINT ck_subscription_prueba
        CHECK ((status = 'PRUEBA') = (prueba_hasta IS NOT NULL));
COMMENT ON COLUMN subscription.status IS 'PRUEBA | ACTIVA | SUSPENDIDA | CANCELADA. CANCELADA es terminal. PRUEBA vencida (prueba_hasta pasado) se lee como SUSPENDIDA: solo lectura';
COMMENT ON COLUMN subscription.prueba_hasta IS 'Fin de la prueba gratis, instante UTC. Obligatoria en PRUEBA y nula en cualquier otro estado';

-- Servicios contratados: una fila por servicio.
CREATE TABLE subscription_servicio
(
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    organization_id bigint NOT NULL,
    servicio varchar(24) NOT NULL,
    created_at timestamptz(6) NOT NULL,
    CONSTRAINT pk_subscription_servicio PRIMARY KEY (id),
    CONSTRAINT uk_subscription_servicio UNIQUE (organization_id, servicio),
    CONSTRAINT fk_subscription_servicio_org FOREIGN KEY (organization_id) REFERENCES organization (id),
    CONSTRAINT ck_subscription_servicio CHECK (servicio IN ('KINESIOLOGIA', 'ACTIVIDADES'))
);
COMMENT ON TABLE subscription_servicio IS 'Servicios que el centro tiene contratados: KINESIOLOGIA (clinica, coberturas, presentaciones) y ACTIVIDADES (clases, pases, abonos). Al cambiar la contratacion se reemplazan las filas. Propietario: modulo organization';

-- Adicionales contratados: hoy solo IA.
CREATE TABLE subscription_adicional
(
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    organization_id bigint NOT NULL,
    adicional varchar(24) NOT NULL,
    created_at timestamptz(6) NOT NULL,
    CONSTRAINT pk_subscription_adicional PRIMARY KEY (id),
    CONSTRAINT uk_subscription_adicional UNIQUE (organization_id, adicional),
    CONSTRAINT fk_subscription_adicional_org FOREIGN KEY (organization_id) REFERENCES organization (id),
    CONSTRAINT ck_subscription_adicional CHECK (adicional IN ('IA'))
);
COMMENT ON TABLE subscription_adicional IS 'Adicionales contratados por el centro. IA: asistente, evolucion, sugerencias, dictado y biblioteca; cada funcion anda solo si ademas el despliegue la ofrece y el centro la prendio. Propietario: modulo organization';

-- Pedidos de prueba desde la landing publica. Global: todavia no hay organizacion.
CREATE TABLE solicitud_de_prueba
(
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre varchar(80) COLLATE akine_ci NOT NULL,
    apellido varchar(80) COLLATE akine_ci NOT NULL,
    email varchar(254) NOT NULL,
    telefono varchar(40),
    nombre_centro varchar(120) COLLATE akine_ci NOT NULL,
    ciudad varchar(120) COLLATE akine_ci,
    kinesiologia boolean NOT NULL,
    actividades boolean NOT NULL,
    sedes varchar(16) NOT NULL,
    interesa_ia boolean NOT NULL,
    comentario varchar(1000) COLLATE akine_ci,
    estado varchar(16) NOT NULL,
    motivo_descarte varchar(500) COLLATE akine_ci,
    organization_id bigint,
    resuelta_por bigint,
    resuelta_en timestamptz(6),
    idempotency_key varchar(80) NOT NULL,
    version bigint DEFAULT 0 NOT NULL,
    created_at timestamptz(6) NOT NULL,
    updated_at timestamptz(6) NOT NULL,
    CONSTRAINT pk_solicitud_de_prueba PRIMARY KEY (id),
    CONSTRAINT uk_solicitud_de_prueba_clave UNIQUE (idempotency_key),
    CONSTRAINT fk_solicitud_de_prueba_org FOREIGN KEY (organization_id) REFERENCES organization (id),
    CONSTRAINT ck_solicitud_de_prueba_estado CHECK (estado IN ('PENDIENTE', 'APROBADA', 'DESCARTADA')),
    CONSTRAINT ck_solicitud_de_prueba_sedes CHECK (sedes IN ('UNA', 'HASTA_TRES', 'MAS_DE_TRES')),
    CONSTRAINT ck_solicitud_de_prueba_servicio CHECK (kinesiologia OR actividades),
    CONSTRAINT ck_solicitud_de_prueba_resolucion
        CHECK ((estado = 'PENDIENTE') = (resuelta_en IS NULL)),
    CONSTRAINT ck_solicitud_de_prueba_aprobada
        CHECK (estado <> 'APROBADA' OR organization_id IS NOT NULL)
);
CREATE INDEX ix_solicitud_de_prueba_estado ON solicitud_de_prueba (estado, created_at);
COMMENT ON TABLE solicitud_de_prueba IS 'Pedidos de prueba gratis desde la landing. Global (ADR-0023): no tiene organizacion hasta que la plataforma la aprueba y crea el centro. Nunca se borra: se aprueba o se descarta con motivo. Propietario: modulo organization';
