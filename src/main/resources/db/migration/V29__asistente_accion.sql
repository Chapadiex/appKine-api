-- =====================================================================================
-- AKINE — Acciones del asistente (docs/diseno/AKINE-asistente-acciones.md, §5.4).
--
-- Una fila por accion propuesta: asistencia de clase, pago, atencion, llegada o datos de
-- paciente. Se graba solo cuando la persona la confirma, una unica vez.
--
-- NO guarda textos: ni la frase, ni nombres, ni la nota clinica. Solo el tipo, los ids de lo
-- propuesto (referencias) y los ids de lo creado (resultado). El contenido de la tarjeta vive
-- en el cliente y vuelve en la confirmacion.
--
-- Sin borrado fisico. "Vencida" no es un estado: es vence_en en el pasado.
-- =====================================================================================

CREATE TABLE asistente_accion
(
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    organization_id bigint NOT NULL,
    consultorio_id bigint NOT NULL,
    cuenta_id bigint NOT NULL,
    tipo varchar(30) NOT NULL,
    estado varchar(20) NOT NULL,
    referencias jsonb NOT NULL,
    resultado jsonb,
    creada_en timestamptz(6) NOT NULL,
    vence_en timestamptz(6) NOT NULL,
    resuelta_en timestamptz(6),
    CONSTRAINT pk_asistente_accion PRIMARY KEY (id),
    CONSTRAINT fk_asistente_accion_org FOREIGN KEY (organization_id) REFERENCES organization (id),
    CONSTRAINT fk_asistente_accion_consultorio FOREIGN KEY (consultorio_id) REFERENCES consultorio (id),
    CONSTRAINT fk_asistente_accion_cuenta FOREIGN KEY (cuenta_id) REFERENCES cuenta (id),
    CONSTRAINT ck_asistente_accion_tipo CHECK (tipo IN ('ASISTENCIA_CLASE', 'PAGO', 'ATENCION', 'LLEGADA',
                                                        'PACIENTE_ALTA', 'PACIENTE_EDICION')),
    CONSTRAINT ck_asistente_accion_estado CHECK (estado IN ('PROPUESTA', 'EN_CURSO', 'CONFIRMADA', 'DESCARTADA'))
);
COMMENT ON TABLE asistente_accion IS 'Acciones que el asistente propuso. Solo ids: sin la frase, sin nombres y sin la nota clinica. Se confirma una sola vez (PROPUESTA -> EN_CURSO -> CONFIRMADA) y vence por vence_en.';

CREATE INDEX ix_asistente_accion_org_cuenta ON asistente_accion (organization_id, cuenta_id, estado);
