CREATE TABLE biblioteca_version
(
    organization_id bigint NOT NULL,
    version bigint DEFAULT 0 NOT NULL,
    CONSTRAINT pk_biblioteca_version PRIMARY KEY (organization_id)
);

CREATE TABLE libro
(
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    organization_id bigint NOT NULL,
    titulo varchar(300) COLLATE akine_ci NOT NULL,
    autores varchar(500) COLLATE akine_ci,
    edicion varchar(100) COLLATE akine_ci,
    area varchar(100) COLLATE akine_ci,
    storage_key varchar(64) COLLATE akine_ci NOT NULL,
    nombre_archivo varchar(255) COLLATE akine_ci NOT NULL,
    content_type varchar(120) COLLATE akine_ci NOT NULL,
    tamano_bytes bigint NOT NULL,
    hash_sha256 varchar(64) COLLATE akine_ci NOT NULL,
    paginas integer,
    estado varchar(20) COLLATE akine_ci DEFAULT 'PENDIENTE' NOT NULL,
    progreso integer DEFAULT 0 NOT NULL,
    motivo_error varchar(500) COLLATE akine_ci,
    intentos integer DEFAULT 0 NOT NULL,
    reemplaza_libro_id bigint,
    activo boolean DEFAULT true NOT NULL,
    hash_activo varchar(64) COLLATE akine_ci GENERATED ALWAYS AS (CASE WHEN activo AND reemplaza_libro_id IS NULL THEN hash_sha256 END) STORED,
    procesando_desde timestamptz(6),
    latido timestamptz(6),
    declaracion_derechos_en timestamptz(6) NOT NULL,
    declaracion_derechos_por_cuenta_id bigint NOT NULL,
    creado_por_cuenta_id bigint NOT NULL,
    version bigint DEFAULT 0 NOT NULL,
    created_at timestamptz(6) NOT NULL,
    updated_at timestamptz(6) NOT NULL,
    version_procesamiento integer DEFAULT 1 NOT NULL,
    CONSTRAINT pk_libro PRIMARY KEY (id),
    CONSTRAINT uk_libro_hash_activo UNIQUE (organization_id, hash_activo),
    CONSTRAINT uk_libro_reemplaza UNIQUE (reemplaza_libro_id),
    CONSTRAINT ck_libro_estado CHECK (estado in ('PENDIENTE','PROCESANDO','LISTO','ERROR')),
    CONSTRAINT ck_libro_progreso CHECK (progreso between 0 and 100)
);
CREATE INDEX ix_libro_estado ON libro (estado, latido);
CREATE INDEX ix_libro_organizacion ON libro (organization_id, activo, titulo);
COMMENT ON COLUMN libro.organization_id IS 'Tenant propietario';
COMMENT ON COLUMN libro.storage_key IS 'Clave opaca del PDF en el almacenamiento. Nunca viaja al cliente';
COMMENT ON COLUMN libro.paginas IS 'Se conoce al terminar de extraer';
COMMENT ON COLUMN libro.intentos IS 'Reclamos del worker desde el alta o el ultimo reproceso; al tercero que vuelve a la cola pasa a ERROR';
COMMENT ON COLUMN libro.reemplaza_libro_id IS 'Libro al que este reemplaza mientras no este LISTO';
COMMENT ON COLUMN libro.hash_activo IS 'Hash solo para libros activos que no son un reemplazo en curso: soporta el unique sin bloquear al reemplazo';
COMMENT ON COLUMN libro.procesando_desde IS 'Identidad del intento del worker: la fija el reclamo y no cambia';
COMMENT ON COLUMN libro.latido IS 'Ultima senal de vida del intento (reclamo y cada avance); el barrido de trabados la compara';
COMMENT ON COLUMN libro.version_procesamiento IS 'Version de la ingesta con la que se armo el indice; menor que la vigente = a reprocesar';

CREATE TABLE libro_fragmento
(
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    organization_id bigint NOT NULL,
    libro_id bigint NOT NULL,
    orden integer NOT NULL,
    pagina_desde integer NOT NULL,
    pagina_hasta integer NOT NULL,
    texto text COLLATE akine_ci NOT NULL,
    vector vector(768),
    modelo_embeddings varchar(100) COLLATE akine_ci,
    sospechoso boolean DEFAULT false NOT NULL,
    CONSTRAINT pk_libro_fragmento PRIMARY KEY (id)
);
CREATE INDEX ix_libro_fragmento_libro ON libro_fragmento (libro_id, organization_id);
CREATE INDEX ix_libro_fragmento_modelo ON libro_fragmento (modelo_embeddings);
CREATE INDEX ix_libro_fragmento_organizacion ON libro_fragmento (organization_id, modelo_embeddings);
COMMENT ON COLUMN libro_fragmento.vector IS 'Embedding de multilingual-e5-base (768 dimensiones). NULL hasta que el worker lo calcula. Invariante: vector IS NULL <=> modelo_embeddings IS NULL';
COMMENT ON COLUMN libro_fragmento.modelo_embeddings IS 'Modelo que calculo el vector; distinto del vigente = a reindexar';

-- -------------------------------------------------------------------------------------
-- Busqueda de la biblioteca en PostgreSQL (reemplaza el FULLTEXT de MySQL y el recorrido en memoria).
--
-- Texto: los libros son en espanol y en ingles y el libro no declara idioma, asi que cada fragmento
-- se indexa con las dos configuraciones y la consulta se arma con las dos. Las dos ignoran tildes
-- (unaccent), como el FULLTEXT de MySQL con utf8mb4_0900_ai_ci, y reducen cada palabra a su raiz:
-- "rodillas" encuentra "rodilla". Terminos anatomicos y tecnicos que el diccionario no conoce
-- quedan como estan, sin raiz, y se encuentran por igualdad.
--
-- Vector: 768 dimensiones, las de multilingual-e5-base (verificadas en el modelo ONNX instalado).
-- Los puntajes son coseno, igual que el recorrido en Java que reemplaza. El indice HNSW es
-- aproximado; la consulta lo usa con recorrido iterativo para no perder filas por el filtro de
-- organizacion y estado (ver PgAlmacenVectorial).
-- -------------------------------------------------------------------------------------
CREATE TEXT SEARCH CONFIGURATION akine_es (COPY = pg_catalog.spanish);
ALTER TEXT SEARCH CONFIGURATION akine_es
    ALTER MAPPING FOR hword, hword_part, word WITH unaccent, spanish_stem;

CREATE TEXT SEARCH CONFIGURATION akine_en (COPY = pg_catalog.english);
ALTER TEXT SEARCH CONFIGURATION akine_en
    ALTER MAPPING FOR hword, hword_part, word WITH unaccent, english_stem;

ALTER TABLE libro_fragmento
    ADD COLUMN texto_tsv tsvector GENERATED ALWAYS AS (
        to_tsvector('akine_es'::regconfig, texto) || to_tsvector('akine_en'::regconfig, texto)) STORED;
COMMENT ON COLUMN libro_fragmento.texto_tsv IS 'Texto indexado en espanol e ingles, sin tildes. Lo calcula la base';

CREATE INDEX ix_libro_fragmento_texto_tsv ON libro_fragmento USING gin (texto_tsv);
CREATE INDEX ix_libro_fragmento_vector ON libro_fragmento USING hnsw (vector vector_cosine_ops);
