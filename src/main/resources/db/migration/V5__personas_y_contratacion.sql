CREATE TABLE autorizacion
(
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    organization_id bigint NOT NULL,
    persona_id bigint NOT NULL,
    consultorio_id bigint NOT NULL,
    cobertura_id bigint NOT NULL,
    orden_medica_id bigint,
    practica_id bigint NOT NULL,
    numero varchar(64) COLLATE akine_ci NOT NULL,
    estado varchar(16) COLLATE akine_ci DEFAULT 'PENDIENTE' NOT NULL,
    motivo varchar(280) COLLATE akine_ci,
    cantidad_autorizada integer,
    cantidad_consumida integer DEFAULT 0 NOT NULL,
    vigencia_desde date NOT NULL,
    vigencia_hasta date,
    convenio_id bigint,
    convenio_codigo varchar(64) COLLATE akine_ci,
    convenio_nombre varchar(160) COLLATE akine_ci,
    requeria_orden boolean,
    requeria_autorizacion boolean,
    requeria_credencial boolean,
    referencia_capturada_el timestamptz(6),
    adjunto_id bigint,
    observaciones varchar(500) COLLATE akine_ci,
    active boolean DEFAULT true NOT NULL,
    deleted_at timestamptz(6),
    deactivation_reason varchar(280) COLLATE akine_ci,
    deleted_key timestamptz(6) GENERATED ALWAYS AS (COALESCE(deleted_at, '1970-01-01 00:00:00+00'::timestamptz)) STORED,
    version bigint DEFAULT 0 NOT NULL,
    created_at timestamptz(6) NOT NULL,
    updated_at timestamptz(6) NOT NULL,
    CONSTRAINT pk_autorizacion PRIMARY KEY (id),
    CONSTRAINT uk_autorizacion_numero_vigente UNIQUE (organization_id, cobertura_id, numero, deleted_key),
    CONSTRAINT ck_autorizacion_baja_coherente CHECK (((active = true) and (deleted_at is null) and (deactivation_reason is null)) or ((active = false) and (deleted_at is not null) and (deactivation_reason is not null))),
    CONSTRAINT ck_autorizacion_cantidad_positiva CHECK ((cantidad_autorizada is null) or (cantidad_autorizada > 0)),
    CONSTRAINT ck_autorizacion_consumo_coherente CHECK ((cantidad_consumida >= 0) and ((cantidad_autorizada is null) or (cantidad_consumida <= cantidad_autorizada))),
    CONSTRAINT ck_autorizacion_estado CHECK (estado in ('PENDIENTE','APROBADA','OBSERVADA','RECHAZADA')),
    CONSTRAINT ck_autorizacion_motivo_exigido CHECK ((estado not in ('OBSERVADA','RECHAZADA')) or (motivo is not null)),
    CONSTRAINT ck_autorizacion_snapshot_coherente CHECK (((convenio_id is null) and (convenio_codigo is null) and (convenio_nombre is null) and (requeria_orden is null) and (requeria_autorizacion is null) and (requeria_credencial is null) and (referencia_capturada_el is null)) or ((convenio_id is not null) and (convenio_codigo is not null) and (convenio_nombre is not null) and (requeria_orden is not null) and (requeria_autorizacion is not null) and (requeria_credencial is not null) and (referencia_capturada_el is not null))),
    CONSTRAINT ck_autorizacion_vigencia_coherente CHECK ((vigencia_hasta is null) or (vigencia_hasta >= vigencia_desde))
);
CREATE INDEX fk_autorizacion_adjunto ON autorizacion (adjunto_id);
CREATE INDEX fk_autorizacion_cobertura ON autorizacion (cobertura_id);
CREATE INDEX fk_autorizacion_consultorio ON autorizacion (consultorio_id);
CREATE INDEX fk_autorizacion_convenio ON autorizacion (convenio_id);
CREATE INDEX fk_autorizacion_orden ON autorizacion (orden_medica_id);
CREATE INDEX fk_autorizacion_persona ON autorizacion (persona_id);
CREATE INDEX fk_autorizacion_practica ON autorizacion (practica_id);
CREATE INDEX ix_autorizacion_cobertura ON autorizacion (organization_id, cobertura_id, practica_id, active, estado);
CREATE INDEX ix_autorizacion_persona ON autorizacion (organization_id, persona_id, active, vigencia_desde);
