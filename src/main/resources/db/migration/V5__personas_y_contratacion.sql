CREATE TABLE adjunto_administrativo
(
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    organization_id bigint NOT NULL,
    persona_id bigint NOT NULL,
    consultorio_id bigint,
    categoria varchar(32) COLLATE akine_ci NOT NULL,
    titulo varchar(160) COLLATE akine_ci,
    nombre_archivo varchar(255) COLLATE akine_ci NOT NULL,
    content_type varchar(120) COLLATE akine_ci NOT NULL,
    tamano_bytes bigint NOT NULL,
    checksum_sha256 varchar(64) COLLATE akine_ci NOT NULL,
    storage_key varchar(64) COLLATE akine_ci NOT NULL,
    estado varchar(24) COLLATE akine_ci DEFAULT 'DISPONIBLE' NOT NULL,
    subido_por bigint NOT NULL,
    subido_en timestamptz(6) NOT NULL,
    active boolean DEFAULT true NOT NULL,
    deleted_at timestamptz(6),
    deactivation_reason varchar(280) COLLATE akine_ci,
    deleted_key timestamptz(6) GENERATED ALWAYS AS (COALESCE(deleted_at, '1970-01-01 00:00:00+00'::timestamptz)) STORED,
    version bigint DEFAULT 0 NOT NULL,
    created_at timestamptz(6) NOT NULL,
    updated_at timestamptz(6) NOT NULL,
    CONSTRAINT pk_adjunto_administrativo PRIMARY KEY (id),
    CONSTRAINT uk_adjunto_contenido_vigente UNIQUE (organization_id, persona_id, checksum_sha256, deleted_key),
    CONSTRAINT uk_adjunto_storage_key UNIQUE (storage_key),
    CONSTRAINT ck_adjunto_baja_coherente CHECK (((active = true) and (deleted_at is null) and (deactivation_reason is null)) or ((active = false) and (deleted_at is not null) and (deactivation_reason is not null))),
    CONSTRAINT ck_adjunto_categoria CHECK (categoria in ('DOCUMENTO_IDENTIDAD','CREDENCIAL_COBERTURA','CONSENTIMIENTO','AUTORIZACION','COMPROBANTE','OTRO')),
    CONSTRAINT ck_adjunto_estado CHECK (estado in ('DISPONIBLE','NO_DISPONIBLE')),
    CONSTRAINT ck_adjunto_tamano CHECK (tamano_bytes > 0)
);
CREATE INDEX fk_adjunto_persona ON adjunto_administrativo (persona_id);
CREATE INDEX ix_adjunto_persona ON adjunto_administrativo (organization_id, persona_id, active, categoria);
COMMENT ON TABLE adjunto_administrativo IS 'Metadata de un documento ADMINISTRATIVO vinculado a una Persona (M07/M25). El binario vive fuera de la base. NO es un contenedor clinico: RN-M25-005. Propietario: modulo person';
COMMENT ON COLUMN adjunto_administrativo.organization_id IS 'Tenant propietario. Todo unique e indice de esta tabla empieza por el (AGENT.md seccion 5)';
COMMENT ON COLUMN adjunto_administrativo.persona_id IS 'Persona a la que se vincula el documento. El acceso al adjunto hereda el de la persona (RN-M25-003)';
COMMENT ON COLUMN adjunto_administrativo.consultorio_id IS 'Sede desde la que se cargo. Dato de auditoria del hecho, NO de propiedad: ver la cabecera. No participa de ningun unique';
COMMENT ON COLUMN adjunto_administrativo.categoria IS 'Clasificacion ADMINISTRATIVA (RF-M25-003). La lista no tiene ninguna categoria clinica a proposito: RN-M25-005';
COMMENT ON COLUMN adjunto_administrativo.titulo IS 'Titulo con el que el operador describe el documento. Opcional: el nombre del archivo ya dice algo';
COMMENT ON COLUMN adjunto_administrativo.nombre_archivo IS 'Nombre original con el que se subio. Se devuelve al descargar y NUNCA participa de la ruta en disco';
COMMENT ON COLUMN adjunto_administrativo.content_type IS 'Tipo DETECTADO por los bytes, no el declarado por el cliente. Un cliente que miente sobre su Content-Type no consigue nada';
COMMENT ON COLUMN adjunto_administrativo.tamano_bytes IS 'Tamano real del contenido almacenado';
