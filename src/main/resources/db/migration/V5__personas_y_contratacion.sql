COMMENT ON COLUMN adjunto_administrativo.storage_key IS 'Clave OPACA del contenido en el almacenamiento. UUID sin guiones, generado por el servidor. NUNCA viaja al cliente (RN-M25-002)';
COMMENT ON COLUMN adjunto_administrativo.estado IS 'DISPONIBLE mientras el contenido se pueda entregar. NO_DISPONIBLE cuando el almacenamiento perdio el binario: la metadata sobrevive y la descarga responde 409, no 404';
COMMENT ON COLUMN adjunto_administrativo.subido_por IS 'accountId del actor que subio el archivo. Sin FK a cuenta: cuenta es de identity y una FK cruzaria la propiedad de datos entre modulos';
