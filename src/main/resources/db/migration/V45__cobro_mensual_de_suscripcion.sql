-- =====================================================================================
-- AKINE — Cobro mensual de la suscripcion (19/11/2026).
--
-- Diseño: docs/diseno/AKINE-cobro-mensual.md. La plataforma registra a mano, mes a mes, que un
-- centro pago. Cada cobro extiende subscription.pagado_hasta y deja una fila de historial. Lo que
-- pasa al vencer (gracia de 3 dias, solo lectura hasta los 18, despues sin acceso) no se
-- materializa: se calcula al leer comparando pagado_hasta con el reloj, como la prueba vencida.
--
-- Nada cambia para quien ya existe: pagado_hasta nulo = sin control de cobro.
-- =====================================================================================

ALTER TABLE subscription ADD COLUMN pagado_hasta timestamptz(6);
COMMENT ON COLUMN subscription.pagado_hasta IS 'Hasta cuando esta pagada, instante UTC. NULL = sin control de cobro (los centros anteriores al 19/11/2026 hasta su primer cobro). Vencido: 3 dias de gracia, solo lectura hasta los 18 dias y despues sin acceso, calculado al leer';

-- Ningun cobro sobre una prueba: registrar el primero la pasa a ACTIVA en la misma escritura.
ALTER TABLE subscription
    ADD CONSTRAINT ck_subscription_pagado_fuera_de_prueba
        CHECK (status <> 'PRUEBA' OR pagado_hasta IS NULL);

-- Partial index para el worker de avisos: solo las suscripciones bajo control de cobro.
CREATE INDEX ix_subscription_pagado_hasta ON subscription (pagado_hasta) WHERE pagado_hasta IS NOT NULL;

CREATE TABLE subscription_cobro
(
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    organization_id bigint NOT NULL,
    subscription_id bigint NOT NULL,
    periodo_desde timestamptz(6) NOT NULL,
    periodo_hasta timestamptz(6) NOT NULL,
    meses integer NOT NULL,
    nota varchar(200) COLLATE akine_ci,
    registrado_por bigint NOT NULL,
    registrado_en timestamptz(6) NOT NULL,
    CONSTRAINT pk_subscription_cobro PRIMARY KEY (id),
    CONSTRAINT fk_subscription_cobro_org FOREIGN KEY (organization_id) REFERENCES organization (id),
    CONSTRAINT fk_subscription_cobro_subscription FOREIGN KEY (subscription_id) REFERENCES subscription (id),
    CONSTRAINT ck_subscription_cobro_meses CHECK (meses BETWEEN 1 AND 12),
    CONSTRAINT ck_subscription_cobro_periodo CHECK (periodo_hasta > periodo_desde)
);
CREATE INDEX ix_subscription_cobro_org ON subscription_cobro (organization_id, registrado_en);
COMMENT ON TABLE subscription_cobro IS 'Historial de cobros que la plataforma registro a un centro. Append-only: jamas UPDATE ni DELETE. Cada fila extiende subscription.pagado_hasta hasta periodo_hasta. Propietario: modulo organization';
COMMENT ON COLUMN subscription_cobro.periodo_desde IS 'max(pagado_hasta anterior, momento del registro): pagar antes de vencer conserva el ciclo, pagar tarde lo reinicia';
COMMENT ON COLUMN subscription_cobro.periodo_hasta IS 'periodo_desde + meses calendario en la zona del centro';
COMMENT ON COLUMN subscription_cobro.registrado_por IS 'Cuenta de plataforma que lo registro. Referencia logica a identity, sin FK fisica (ADR-0001)';
