-- =====================================================================================
-- AKINE — Marca de la organizacion: colores institucionales por tema, datos de contacto
-- para el pie de pagina y logo (uno por tema).
--
-- Dos tablas y no columnas en organization: la marca tiene su propia version (editar el
-- color no choca con editar el nombre del centro) y el logo es un binario que ninguna
-- lectura de la organizacion tiene que arrastrar.
-- =====================================================================================

CREATE TABLE organization_marca
(
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    organization_id bigint NOT NULL,
    color_principal_claro varchar(7),
    color_acento_claro varchar(7),
    color_principal_oscuro varchar(7),
    color_acento_oscuro varchar(7),
    telefono varchar(40) COLLATE akine_ci,
    email varchar(254) COLLATE akine_ci,
    sitio_web varchar(200) COLLATE akine_ci,
    direccion varchar(240) COLLATE akine_ci,
    leyenda varchar(200) COLLATE akine_ci,
    version bigint DEFAULT 0 NOT NULL,
    created_at timestamptz(6) NOT NULL,
    updated_at timestamptz(6) NOT NULL,
    CONSTRAINT pk_organization_marca PRIMARY KEY (id),
    CONSTRAINT uk_organization_marca_org UNIQUE (organization_id),
    CONSTRAINT fk_organization_marca_org FOREIGN KEY (organization_id) REFERENCES organization (id),
    CONSTRAINT ck_organization_marca_colores CHECK (
        (color_principal_claro IS NULL OR color_principal_claro ~ '^#[0-9a-f]{6}$')
        AND (color_acento_claro IS NULL OR color_acento_claro ~ '^#[0-9a-f]{6}$')
        AND (color_principal_oscuro IS NULL OR color_principal_oscuro ~ '^#[0-9a-f]{6}$')
        AND (color_acento_oscuro IS NULL OR color_acento_oscuro ~ '^#[0-9a-f]{6}$'))
);
COMMENT ON TABLE organization_marca IS 'Identidad visual y datos de contacto del tenant. Una fila por organizacion, creada en la primera edicion. Un color NULL significa "el de AKINE".';
COMMENT ON COLUMN organization_marca.color_principal_claro IS 'Color de accion (botones, foco) en tema claro, #rrggbb en minusculas';
COMMENT ON COLUMN organization_marca.color_acento_claro IS 'Color de enlaces y de la seleccion en tema claro';
COMMENT ON COLUMN organization_marca.leyenda IS 'Linea libre del pie de pagina: horario, matricula, lema';

CREATE TABLE organization_logo
(
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    organization_id bigint NOT NULL,
    variante varchar(8) NOT NULL,
    content_type varchar(32) NOT NULL,
    contenido bytea NOT NULL,
    tamano_bytes integer NOT NULL,
    sha256 varchar(64) NOT NULL,
    created_at timestamptz(6) NOT NULL,
    updated_at timestamptz(6) NOT NULL,
    CONSTRAINT pk_organization_logo PRIMARY KEY (id),
    CONSTRAINT uk_organization_logo_org_variante UNIQUE (organization_id, variante),
    CONSTRAINT fk_organization_logo_org FOREIGN KEY (organization_id) REFERENCES organization (id),
    CONSTRAINT ck_organization_logo_variante CHECK (variante IN ('CLARO', 'OSCURO')),
    CONSTRAINT ck_organization_logo_tipo CHECK (content_type IN ('image/png', 'image/jpeg', 'image/webp'))
);
COMMENT ON TABLE organization_logo IS 'Logo del tenant, uno por tema. Es configuracion, no historia: reemplazarlo pisa la fila y quitarlo la borra; el hecho queda en audit_event.';
COMMENT ON COLUMN organization_logo.content_type IS 'Decidido por los bytes del archivo, nunca por lo que declara el cliente. SVG no se admite: puede traer script';
COMMENT ON COLUMN organization_logo.sha256 IS 'Huella del contenido: el cliente la usa para saber si cambio';
