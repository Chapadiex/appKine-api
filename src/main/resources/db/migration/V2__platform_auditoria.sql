CREATE TABLE audit_event
(
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    organization_id bigint,
    consultorio_id bigint,
    actor_account_id bigint,
    event_type varchar(64) COLLATE akine_ci NOT NULL,
    entity_type varchar(64) COLLATE akine_ci NOT NULL,
    entity_id bigint,
    previous_state varchar(64) COLLATE akine_ci,
    new_state varchar(64) COLLATE akine_ci,
    details jsonb,
    reason varchar(500) COLLATE akine_ci,
    correlation_id varchar(64) COLLATE akine_ci,
    occurred_at timestamptz(6) NOT NULL,
    agenda_membership_ref varchar(32) COLLATE akine_ci GENERATED ALWAYS AS (left(COALESCE(details ->> 'profesionalMembershipId', details ->> 'membershipId'), 32)) STORED,
    agenda_membership_anterior_ref varchar(32) COLLATE akine_ci GENERATED ALWAYS AS (left(details ->> 'profesionalAnteriorId', 32)) STORED,
    agenda_turno_origen_ref varchar(32) COLLATE akine_ci GENERATED ALWAYS AS (left(details ->> 'turnoOrigenId', 32)) STORED,
    CONSTRAINT pk_audit_event PRIMARY KEY (id)
);
CREATE INDEX ix_audit_event_actor ON audit_event (organization_id, actor_account_id, occurred_at);
CREATE INDEX ix_audit_event_agenda ON audit_event (organization_id, agenda_membership_ref, occurred_at);
CREATE INDEX ix_audit_event_agenda_anterior ON audit_event (organization_id, agenda_membership_anterior_ref, occurred_at);
CREATE INDEX ix_audit_event_agenda_turno_origen ON audit_event (organization_id, agenda_turno_origen_ref);
CREATE INDEX ix_audit_event_entity ON audit_event (organization_id, entity_type, entity_id, occurred_at);
CREATE INDEX ix_audit_event_org_loc_time ON audit_event (organization_id, consultorio_id, occurred_at);
CREATE INDEX ix_audit_event_org_time ON audit_event (organization_id, occurred_at);
COMMENT ON TABLE audit_event IS 'Auditoria append-only. Jamas UPDATE ni DELETE: por eso no tiene updated_at, ni baja logica, ni version. Jamas secretos ni contenido clinico. Sin FK a organization para que la auditoria sobreviva a cualquier operacion sobre el tenant.';
COMMENT ON COLUMN audit_event.organization_id IS 'NULL SOLO para eventos de plataforma sin tenant (p.ej. alta de un plan). Todo evento de negocio lo lleva';
COMMENT ON COLUMN audit_event.consultorio_id IS 'NULL cuando el hecho no pertenece a una sede concreta';
COMMENT ON COLUMN audit_event.actor_account_id IS 'NULL = sistema. Referencia logica a identity.account, sin FK fisica (ADR-0001)';
COMMENT ON COLUMN audit_event.event_type IS 'Que paso: ORGANIZATION_CREATED, SUBSCRIPTION_TRANSITIONED, CONTEXT_SELECTED, ...';
COMMENT ON COLUMN audit_event.entity_type IS 'Sobre que entidad: Organization, Subscription, Membership, ...';
COMMENT ON COLUMN audit_event.entity_id IS 'NULL cuando el evento no apunta a una fila concreta';
COMMENT ON COLUMN audit_event.details IS 'Contexto adicional del evento. JAMAS secretos, tokens, contrasenas ni contenido clinico';
COMMENT ON COLUMN audit_event.reason IS 'Motivo declarado por el actor cuando la operacion lo exige';
COMMENT ON COLUMN audit_event.correlation_id IS 'Correlaciona el evento con el log estructurado del request (ADR-0005)';
COMMENT ON COLUMN audit_event.occurred_at IS 'Instante UTC del hecho';
COMMENT ON COLUMN audit_event.agenda_membership_ref IS 'Membership del profesional del evento de agenda, derivada de details. No se escribe.';
COMMENT ON COLUMN audit_event.agenda_membership_anterior_ref IS 'Membership del profesional ANTES de una reprogramacion, derivada de details. No se escribe.';
COMMENT ON COLUMN audit_event.agenda_turno_origen_ref IS 'Turno de origen de un turno trasladado, derivado de details. No se escribe.';

CREATE TABLE platform_schema_info
(
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    baseline_stage varchar(32) COLLATE akine_ci NOT NULL,
    application_version varchar(32) COLLATE akine_ci NOT NULL,
    contract_version varchar(32) COLLATE akine_ci NOT NULL,
    applied_at timestamptz(6) NOT NULL,
    CONSTRAINT pk_platform_schema_info PRIMARY KEY (id)
);
COMMENT ON TABLE platform_schema_info IS 'Procedencia del esquema. Propiedad del modulo platform. Sin datos de negocio.';
COMMENT ON COLUMN platform_schema_info.baseline_stage IS 'Etapa del plan que establecio el baseline';
COMMENT ON COLUMN platform_schema_info.application_version IS 'Version de la aplicacion que lo aplico';
COMMENT ON COLUMN platform_schema_info.contract_version IS 'Version SemVer del contrato OpenAPI';
COMMENT ON COLUMN platform_schema_info.applied_at IS 'Instante UTC de aplicacion';
